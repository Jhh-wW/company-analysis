"""공시 표가 «문장인 척» 실리는 것을 막는다.

★ 사람이 읽을 수 없는 숫자·머리말 나열은 **채워진 것으로 세지 않는다.**
  세면 자소서에 한 글자도 못 쓰는 칸이 성립 판정을 통과시킨다.

⚠️ 이 시험의 «위험한 쪽»은 오거부다 — 규칙을 조이면
  「매출액 2조 6,499억원으로 전년 대비 17% 성장」 같은 **가장 좋은 문장**이 죽는다.
  그래서 절반이 「멀쩡한 문장을 안 버린다」 안전핀이다.
"""

from __future__ import annotations

import pytest

from src.features.grading.logic import is_table_dump

# ══════════════════════════════════════════════════════════
# 띄어쓰기가 섞인 단위 표기
# ══════════════════════════════════════════════════════════
# ★ 실제 공시는 「(단위 : 천원)」처럼 공백을 넣는다. 그런데 머리말 목록은
#   「(단위:」로 «글자 그대로» 대조해서 이걸 놓쳤다. 그 결과 머리말이
#   1개(「당기」)만 세어져 문턱(2개)에 미달했고, **표가 문장으로 실렸다.**


def test_띄어쓰기가_섞인_단위_표기도_잡는다():
    """★ 띄어쓰기가 섞인 단위 표기도 표로 잡는다 — 하이브 9번 칸에 실제로 실렸던 글이다."""
    실제로_실렸던_표 = (
        "(2) 특수관계자와의 주요 거래 내역 당기 (단위 : 천원) 특수관계자거래 "
        "매출 등 비유동자산 처분 매입 등 비유동자산 취득 전체 특수관계자"
    )

    assert is_table_dump(실제로_실렸던_표)


@pytest.mark.parametrize(
    "표기",
    ["(단위:천원)", "(단위 : 천원)", "( 단위 : 백만원 )", "(단위： 원)"],
)
def test_단위_표기_여러_모양을_다_센다(표기: str):
    from src.features.grading.logic import count_table_headers

    assert count_table_headers(f"당기 {표기} 매출 비용") >= 2


def test_단위_표기를_두_번_세지_않는다():
    """★ 「(단위:」가 이미 목록에 걸렸는데 또 세면 문턱이 헐거워진다."""
    from src.features.grading.logic import count_table_headers

    assert count_table_headers("(단위:천원) 매출") == 1


# ── ★ 오거부 방지 — 여기가 이 수정의 «위험한 쪽»이다 ──


def test_구분하여_라는_말이_든_멀쩡한_문장은_안_버린다():
    """★ 목록 «전체»를 공백 무시로 바꾸면 이 문장이 죽는다.

    「구 분」이 「구분하여」에 걸리기 때문이다. 실측으로 확인했고,
    그래서 **「(단위」만** 넓혔다.
    """
    멀쩡한_문장 = (
        "당사는 매출을 음반ㆍ음원, 공연, 광고ㆍ출연료, MD 및 라이선싱, 콘텐츠, "
        "팬클럽 등으로 구분하여 관리하고 있습니다."
    )

    assert not is_table_dump(멀쩡한_문장)


@pytest.mark.parametrize(
    "문장",
    [
        "2025년 당사의 연결기준 매출액은 2조 6,499억원으로 전년 대비 17% 성장했습니다.",
        "당기순이익 1,683억원을 기록하며 창사 이래 최대 실적을 냈습니다.",
        "회사는 단위 조직을 개편해 의사결정 속도를 높였습니다.",
    ],
)
def test_좋은_문장은_그대로_살린다(문장: str):
    assert not is_table_dump(문장)


# ══════════════════════════════════════════════════════════
# 목차 줄도 «최종 판정»에서 막는다
# ══════════════════════════════════════════════════════════
# ★ 왜 여기에도 거나 — 목차를 고치는 곳(`filingclean.repair`)은 **못 고칠 수 있다.**
#   못 고치면 목차가 그대로 남는데, 목차 줄은
#     · 한글이 있어서 `is_unusable_candidate`(한글 없으면 버림)에 «안» 걸리고
#     · 쪽번호에 천 단위 쉼표가 없어서 숫자 신호에도 «안» 걸린다.
#   즉 **최종 방어선을 통째로 통과해 보고서에 실린다.** 실제로 뚫리는 것을 확인했다.
#
# ★ 정본이 못 박은 원칙 그대로다 — 「형태 검사를 «최종 판정»에도 반드시 건다」
# AI 판정만 믿으면 사고가 재발한다.


def test_목차_줄은_최종_판정에서_막힌다():
    """★ 목차 줄은 최종 판정에서 막는다 — 고치기 전에는 이 글이 보고서에 실릴 수 있었다."""
    목차 = (
        "사업의 내용 ----------------------- 15 III. 재무에 관한 사항 "
        "----------------------- 40 1. 요약재무정보 ----------------------- 40"
    )

    assert is_table_dump(목차)


def test_목차는_다른_방어선을_전부_통과한다():
    """★ 이 시험이 「왜 여기에 걸어야 하는지」를 증명한다.

    다른 검사들이 목차를 못 잡는다는 사실 자체를 못 박아 둔다 —
    나중에 누가 「중복 아닌가」 하고 지우지 못하게.
    """
    from src.features.spanselect.logic import is_unusable_candidate

    목차 = "재무제표 ----------------------- 42 3. 연결재무제표 주석 ----------------------- 49"

    assert not is_unusable_candidate(목차), "한글이 있어서 여기는 통과한다"


def test_쪽번호가_있어도_좋은_문장은_안_버린다():
    """★ 오거부 방지 — 숫자가 든 «가장 좋은 문장»이 죽으면 안 된다."""
    좋은_문장 = "2025년 당사의 연결기준 매출액은 2조 6,499억원으로 전년 대비 17% 성장했습니다."

    assert not is_table_dump(좋은_문장)
