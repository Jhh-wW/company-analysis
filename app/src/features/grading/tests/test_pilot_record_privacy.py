"""시범 자료(실행 기록·조각·보고서)의 공개 저장소 위생 시험.

개인정보를 공개 저장소에 올리지 않는다는 제품 원칙을 기계로 못 박는다.
1판 파일럿 기록에는 실제 회사의 대표자 실명이 `확인카드.대표`에 그대로
남아 있었고, 공시 표와 기사 본문에는 임원·연구인력·기자의 실명이 남아 있었다.
사람이 눈으로 훑어서는 다시 들어오는 것을 막지 못한다.

이 파일이 채점(grading) 폴더에 있는 이유는, 같은 파일럿 자료를 지키는
`test_grading.py`의 fixture 정합 시험과 한자리에서 같이 읽히게 하기 위함이다.
"""

from __future__ import annotations

import json
import re

import pytest

from src.core import paths


#: 대표자 자리에 들어가야 하는 «단 하나의» 값. 생산 상수를 import 하지 않고
#: 리터럴로 적는다 — 생산 쪽이 바뀌면 이 시험이 먼저 깨져야 하기 때문이다.
_MASKED = "(비공개)"

#: 한국 사람 이름꼴(한글 2~4자). 실명이 다시 들어오면 여기에 걸린다.
_KOREAN_NAME = re.compile(r"^[가-힣]{2,4}$")

#: 표·공시에서 «직함이 이름 앞»에 오는 자리 — 「사외이사 홍○○」.
#: ⚠️ 홑낱말 「이사」는 여기 넣지 않는다. 「이사 선임의 건」의 「선임」이 이름으로
#:   잡혀 깨끗한 공시에서도 시험이 빨개진다(실측).
_직함_먼저 = ("사내이사", "사외이사", "감사위원")

#: 기사·명단에서 «이름이 직함 앞»에 오는 자리 — 「홍○○ 부사장」·「홍○○ 이사」.
_이름_먼저 = ("연구소장", "부문장", "부사장", "연구원", "기자", "교수", "이사")


def _고른다(직함들: tuple[str, ...]) -> str:
    """직함을 정규식 선택지로 엮는다.

    긴 것부터 놓는다 — 안 그러면 「사외이사」가 「이사」로 잘려 나간다.

    Args:
        직함들: 엮을 직함.

    Returns:
        「사외이사|사내이사|…」 꼴의 선택지 글자.
    """
    return "|".join(sorted(직함들, key=len, reverse=True))


#: 흔한 한국 성씨. ★ 이 울타리가 오탐을 막는다 — 없으면 「정기주총 사내이사」의
#:   「정기주총」, 「연구부문부문장」의 「연구부문」까지 이름으로 잡혀 깨끗한
#:   자료에서도 시험이 빨개진다(실측). 성씨로 시작하지 않는 낱말은 이름으로 안 본다.
#:   대신 아주 드문 성씨는 놓친다 — 그건 「대표」 두 꼴과 사람 눈이 맡는다.
_성씨 = (
    "김이박최정강조윤장임한오서신권황안송전홍유고문양손배백허남심노하곽성차주우구"
    "원천방공현함변염여추도소석선설마길위표명기반옥육인맹제탁국어은편용진지엄채나"
    "라민예봉피"
)

#: 이름 = 성씨 한 글자 + 한글 1~3자.
#: ★ 가린 이름(「백○○」)은 「○」가 한글이 아니라서 여기에 안 걸린다 — 의도한 것이다.
_이름 = rf"[{_성씨}][가-힣]{{1,3}}"

#: 기사에서 이름과 직함 사이에 끼는 소속. 「김○○ ××증권 연구원」.
#: ★ 아무 낱말이나 받으면 「신규 채용 연구원」의 「신규」가 이름이 된다 —
#:   기관 이름으로 끝나는 낱말만 소속으로 본다(실측).
_소속꼬리 = _고른다(
    (
        "증권", "일보", "신문", "방송", "뉴스", "미디어", "대학교", "대학",
        "연구소", "은행", "경제", "타임스", "저널", "그룹", "전자", "제약",
    )
)
_소속 = rf"[가-힣A-Za-z0-9·]{{0,10}}(?:{_소속꼬리})"

#: 이름·직함 뒤에 붙는 조사. 「김○○ ××증권 연구원은」의 「은」을 못 넘기면
#: 기사 문장의 이름을 통째로 놓친다.
_조사 = r"(?:[은는이가의과와도을를로에씨]|께서)?(?![가-힣])"

#: 이름이 아니라 «직함을 꾸미는 말». 성씨로 시작해 이름처럼 보이지만 사람이 아니다.
#: (「선임 연구원」·「전문 연구원」·「신규 채용」 — 실측 오탐에서 뽑았다.)
_직함_꾸밈말 = frozenset(
    {
        "선임", "책임", "수석", "전문", "주임", "전임", "객원", "초빙", "겸임",
        "명예", "특임", "상근", "사내", "사외", "최고", "우수", "신규", "전담",
        "담당", "현직", "전직", "채용", "임용",
    }
)

#: 기사·공시 본문에서 사람 이름이 나오는 꼴.
#: ★ 실명을 리터럴로 적지 않는다 — 시험 파일에 적으면 지운 이름이 저장소에
#:   그대로 되돌아온다. 대신 «이름이 놓이는 자리»를 본다. 그래서 이 시험은
#:   지운 이름뿐 아니라 앞으로 들어올 어떤 이름도 잡는다.
_PERSON_NAME_SHAPES = (
    ("「대표 ○○○」꼴", re.compile(r"대표\s+(?P<이름>[가-힣]{2,4})")),
    ("「○○○ 대표」꼴", re.compile(r"(?P<이름>[가-힣]{2,4})\s+대표(?!이사)")),
    # 직함이 앞에 오는 꼴 — 「사외이사 배○○」.
    # ⚠️ 직함 앞에 «한글이 없어야 한다»는 조건을 일부러 안 건다. 공시 표를 글자로
    #    뽑으면 「○○○사외이사 △△△」처럼 앞 이름과 직함이 붙어 나오는데,
    #    조건을 걸면 그 뒤의 △△△를 통째로 놓친다(실측).
    (
        "「직함 뒤 이름」꼴",
        re.compile(rf"(?:{_고른다(_직함_먼저)})\s+(?P<이름>{_이름}){_조사}"),
    ),
    # 표를 글자로 뽑으면 이름과 다음 칸의 직함이 붙는다 — 「백○○사외이사」.
    (
        "「이름에 직함이 붙은 표」꼴",
        re.compile(
            rf"(?<![가-힣])(?P<이름>{_이름})"
            rf"(?:{_고른다(_직함_먼저 + _이름_먼저)}){_조사}"
        ),
    ),
    # 이름이 앞에 오는 꼴 — 「원○○ 부사장」·「김○○ ××증권 연구원은」.
    (
        "「이름 뒤 직함」꼴",
        re.compile(
            rf"(?<![가-힣])(?P<이름>[{_성씨}][가-힣]{{1,2}})\s+"
            rf"(?:{_소속}\s+)?(?:{_고른다(_이름_먼저)}){_조사}"
        ),
    ),
)


def _걸린_이름(본문: str) -> list[str]:
    """본문에서 사람 이름으로 보이는 자리를 전부 모은다.

    Args:
        본문: 훑을 글자.

    Returns:
        「꼴 이름: 걸린 자리」 목록. 걸린 것이 없으면 빈 목록.
    """
    걸린것: list[str] = []
    for 꼴이름, 꼴 in _PERSON_NAME_SHAPES:
        for m in 꼴.finditer(본문):
            if m.group("이름") in _직함_꾸밈말:
                continue  # 이름이 아니라 직함을 꾸미는 말이다
            걸린것.append(f"{꼴이름}: {m.group(0)}")
    return 걸린것


def _실행기록() -> list[dict]:
    """`runs.jsonl`을 줄마다 읽는다."""
    with paths.PILOT_RUNS_FILE.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def _대표자_값(record: dict) -> list[str]:
    """한 기록의 모든 단계에서 확인카드의 대표자 값을 모은다."""
    값: list[str] = []
    for step in record.get("steps", []):
        card = step.get("확인카드") if isinstance(step, dict) else None
        if isinstance(card, dict) and "대표" in card:
            값.append(str(card["대표"]))
    return 값


def test_시범_실행기록에_대표자_실명이_없다():
    """★ 공개 저장소에 실제 사람 이름을 올리지 않는다 (제품 원칙).

    대표자 자리는 고정 문자열 하나여야 하고, 사람 이름꼴이 남아 있으면 안 된다.
    """
    if not paths.PILOT_RUNS_FILE.exists():
        pytest.skip("파일럿 실행 기록이 없습니다 (analysis_engine 미배치)")

    기록들 = _실행기록()

    # ★ 필드가 통째로 사라져도 «조용히 통과»하지 않게, 먼저 찾았는지를 센다.
    대표자_있는_줄 = [i for i, r in enumerate(기록들, start=1) if _대표자_값(r)]
    assert len(대표자_있는_줄) == len(기록들), (
        f"확인카드 대표 칸을 못 찾은 줄이 있습니다: "
        f"{sorted(set(range(1, len(기록들) + 1)) - set(대표자_있는_줄))}"
    )

    가려지지_않은 = [
        (줄, 값)
        for 줄, r in enumerate(기록들, start=1)
        for 값 in _대표자_값(r)
        if 값 != _MASKED
    ]
    assert not 가려지지_않은, (
        f"대표자 칸이 «{_MASKED}»가 아닙니다: {가려지지_않은}"
    )

    이름꼴 = [
        (줄, 값)
        for 줄, r in enumerate(기록들, start=1)
        for 값 in _대표자_값(r)
        if _KOREAN_NAME.match(값)
    ]
    assert not 이름꼴, f"대표자 칸에 사람 이름꼴이 남아 있습니다: {이름꼴}"


def _시범_자료_파일() -> list:
    """조각(JSON)과 보고서(md) 전부."""
    조각 = sorted((paths.PILOT_DIR / "fragments").glob("*.json"))
    보고서 = sorted(paths.PILOT_REPORTS_DIR.glob("*.md"))
    return 조각 + 보고서


def test_시범_조각과_보고서에_사람_실명이_없다():
    """★ 공시 표·기사 본문에 실린 사람 이름도 공개 저장소에 올리지 않는다.

    `runs.jsonl`의 구조화 필드만 가리면 대표자가 아닌 사람 — 임원·연구인력·
    기자 — 의 이름이 본문에 그대로 남는다.
    """
    if not paths.demo_data_available():
        pytest.skip("파일럿 자료가 없습니다 (analysis_engine 미배치)")

    파일들 = _시범_자료_파일()
    assert 파일들, "시범 자료를 한 개도 못 찾았습니다 — 시험이 조용히 통과할 뻔했습니다"

    걸린것: list[str] = [
        f"{path.name} {걸린}"
        for path in 파일들
        for 걸린 in _걸린_이름(path.read_text(encoding="utf-8"))
    ]
    assert not 걸린것, (
        "사람 이름이 남아 있습니다 — 「성+○○」으로 가리세요: " + str(걸린것[:5])
    )


