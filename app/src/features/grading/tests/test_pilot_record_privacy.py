def test_이름꼴은_직함_옆_이름을_잡고_가린_이름은_넘긴다():
    """★ 규칙 자체를 시험한다 — 자료가 깨끗해지면 위 전수 시험은 «조용히» 통과한다.

    직함이 붙은 자리의 이름은 반드시 걸리고, 가린 표기(「홍○○」)는 걸리면 안 된다.
    """
    못_잡은 = [보기 for 보기 in _잡아야_하는_보기 if not _걸린_이름(보기)]
    assert not 못_잡은, f"직함 옆 이름을 못 잡았습니다: {못_잡은}"

    잘못_잡은 = [
        (보기, 걸린)
        for 보기 in _넘겨야_하는_보기
        if (걸린 := _걸린_이름(보기))
    ]
    assert not 잘못_잡은, f"이름이 아닌 자리를 잡았습니다: {잘못_잡은}"
