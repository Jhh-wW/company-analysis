"""등급 판정이 쓰는 값 중 **이 폴더에서만 쓰는 것**.

★ 규칙 — 이 값들을 코드 여기저기에 문자열로 박지 않는다.
   기획서를 고치면 여기도 같이 고친다 (`src/core/constants.py`와 같은 원칙).

여러 feature가 같이 쓰는 값(표 덩어리 판정 등)은 `src/core/constants.py`에 있다.
여기 있는 것은 **회계 정형 문구 걸러내기 하나**다.
"""

from __future__ import annotations

from typing import Final

# ── 회계 정형 문구 걸러내기 (문제로그 P-40) ──────────────
#
# 1번 칸에 「수익인식모형 연결회사의 고객과의 계약에서 생기는 수익은 …」 같은
# **회계기준 설명 문구**가 실렸다. 회사 이름을 바꿔도 그대로 말이 되므로
# 자소서에 한 글자도 못 쓴다. 그런데 알맹이 검사(①-b)를 통과했다.
#
# ★★ 가장 중요한 설계 제약 — 「회계 낱말」을 세지 않는다 ★★
#   「매출」·「수익」·「자산」이 들어갔다고 거르면
#   「2025년 연결기준 매출액 5,363억원 … 실적을 달성하였습니다」 같은
#   **보고서에서 가장 좋은 문장**이 통째로 버려진다.
#   정본 §D12-b에 똑같은 사고 기록이 있다 (표 머리말 문턱을 1로 낮췄던 건).
#
#   → 거르는 것은 낱말이 아니라 **「회계기준을 어떻게 적용하는지 설명하는 문형」**이다.
#     「수익을 **창출**」(살림) vs 「수익으로 **인식**」(거름) — 한 글자를 가른다.
#
# ⚠️ 아래 목록을 늘릴 때마다 실측 문장 전체에 다시 돌려본다 (정본 D12-b 절차).
#    `tests/test_grading.py`의 전수 회귀 시험이 이 절차를 자동으로 돌린다.

#: ① 회계기준 주석에만 나오는 낱말. **하나만 있어도** 회계 문구로 본다.
#: 고른 기준 — 사업 설명·실적 문장에는 «절대» 나오지 않는 말만 넣는다.
#: 실측 확인 — 파일럿 조각 원문 1,426문장에 돌려 사업 설명·실적 문장 적중 0건.
ACCOUNTING_STANDARD_TERMS: Final[tuple[str, ...]] = (
    # 수익인식 5단계 모형 용어
    "수행의무", "거래가격", "개별판매가격", "변동대가", "지급청구권", "대체용도",
    # 측정·평가 용어
    "공정가치", "손상차손", "감가상각", "상각후원가", "유효이자율",
    # 계정 이름 중 «회계처리 설명에서만» 쓰이는 것
    "이연법인세", "충당부채", "사용권자산", "리스부채", "환불부채",
    # 기준서 자체를 가리키는 말
    "기업회계기준", "한국채택국제회계기준", "회계정책", "회계처리",
)

#: ② 「무엇을」 — 회계가 다루는 대상어. **이것만으로는 아무것도 거르지 않는다.**
_OBJECT: Final[str] = (
    r"(?:수익|매출|수수료|자산|부채|비용|손실|이익|원가|대가|로열티|법인세|배당금)"
)

#: 대상어 뒤에 오는 조사. ★ 조사를 **반드시** 요구한다.
#: 없으면 합성어 「수익인식 (1) 재화의 판매 …」까지 걸려 사업 설명이 버려진다 (실측).
_PARTICLE: Final[str] = r"(?:으로|로|을|를|은|는)"

#: 대상어와 서술어 사이에 낄 수 있는 글자 수 상한.
#: 「수익으로 인식」은 0자, 「부채를 차감하며 수익을 인식」처럼 몇 글자 끼는 경우가 있다.
#: 넓힐수록 엉뚱한 짝이 맺어져 오거부가 는다 — 실측에서 10자면 충분했다.
ACCOUNTING_GAP_MAX: Final[int] = 10

#: 회계 「적용」 동사의 어간. 「창출·달성·성장」이 여기 없는 것이 이 규칙의 핵심이다.
_VERB_STEM: Final[str] = r"(?:인식|측정|상각|계상)"

#: ★ **종결형만** 받는다. 관형형(「…수익을 인식하는 톡비즈(광고)와 포털비즈는 …」)은
#:   회계 설명이 아니라 **사업 설명**이라 반드시 살려야 한다 (실측 — 카카오 조각).
_VERB_ENDING: Final[str] = (
    r"(?:하고 있|합니다|하였|한다|하며|하거나|하지 않|되고 있|됩니다|된다|되었)"
)

#: ③ 회계기준 «적용 설명» 문형. 하나라도 맞으면 회계 문구로 본다.
ACCOUNTING_POLICY_PATTERNS: Final[tuple[str, ...]] = (
    # 「수익인식모형 …」 「수익인식 시기」 — 뒤에 오는 말까지 봐야 주석 제목이다.
    # 「수익인식」만으로 거르면 「수익인식 (1) 재화의 판매 …」 같은 사업 설명이 죽는다.
    r"수익인식\s*(?:모형|기준|시기|방법|정책|여부)",
    # 「수익으로 인식하고 있습니다」 「비용으로 인식합니다」 — 대상 + 조사 + 적용 동사
    _OBJECT
    + _PARTICLE
    + r"\s*"
    + rf".{{0,{ACCOUNTING_GAP_MAX}}}?"
    + _VERB_STEM
    + _VERB_ENDING,
)

#: 회계 문구로 걸러낸 칸에 붙이는 사유.
#: ★ AI가 아니라 프로그램이 붙인다 (07_출력 근거 ②) — 조용히 지우지 않는다.
#: 어투는 `core/constants.py`의 `TABLE_DUMP_REASON`에 맞췄다.
ACCOUNTING_POLICY_REASON: Final[str] = (
    "찾은 문장이 회계기준을 설명하는 문구라 보류했습니다 "
    "(회사 이름을 바꿔도 말이 되는 문장은 지원동기에 쓸 수 없습니다)"
)
