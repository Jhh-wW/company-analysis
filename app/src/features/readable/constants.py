"""공시 문투를 «읽히는 말»로 바꾸는 규칙 (문제로그 P-107).

★ 왜 하나 — 사용자 지적: 「그냥 DART를 뜯어온 거라서, 이러면 그냥 DART를 직접 보지」.
  공시는 회사가 «자기를 1인칭으로» 쓴 글이라 「당사는 …하고 있습니다」 투다.
  읽는 사람(취준생)에게는 남의 회사 이야기인데 주어가 「당사」면 어색하다.

★ 증권사 리포트는 «3인칭 관찰자» 시점으로 바꿔 쓴다 (조사 9건, 2026-08-16):
    공시  「당사는 순수지주회사로서 … 하고 있습니다」
    리포트「두산인프라코어의 지역별 매출을 살펴보면 … 구성하고 있다」
  **주어와 어미가 통째로 바뀐다.**

⚠️ **이건 «표시용»이다. 원문은 반드시 따로 보관한다.**
  검증(W3 원문 대조)은 «원문»으로 돌아야 한다 — 바꾼 글자로 대조하면 통과할 수 없다.

★ 바꾸는 것은 **정해 둔 낱말·어미뿐**이다. AI를 안 쓴다 —
  환각이 생길 자리가 아예 없다. 못 알아보는 모양은 **그냥 둔다**(원문 유지).
"""

from __future__ import annotations

import re
from typing import Final

# ══════════════════════════════════════════════════════════
# ① 주어 — 「당사」를 회사 이름으로
# ══════════════════════════════════════════════════════════

#: 회사가 자기를 가리키는 말. 뒤에 조사가 붙어야 바꾼다.
#: ⚠️ **「당사자」·「연결회사채」 같은 말에 걸리면 안 된다.**
#:   그래서 «낱말 + 조사» 형태로만 잡는다.
SELF_TERMS: Final[tuple[str, ...]] = (
    "당사", "본사", "당회사", "당해회사", "연결회사", "지배회사", "회사",
)

#: 뒤에 올 수 있는 조사. 이게 붙어야 «주어로 쓰인 것»으로 본다.
SELF_PARTICLES: Final[tuple[str, ...]] = (
    "는", "가", "의", "에서", "에게", "와", "과", "도", "를", "은", "이",
)

#: 주어 치환 규칙 — 「당사는」·「연결회사의」 …
#: ★ 긴 것부터 찾는다. 「당해회사」가 「회사」보다 먼저 걸려야 한다.
SELF_RE: Final[re.Pattern[str]] = re.compile(
    "(?<![가-힣])(" + "|".join(sorted(SELF_TERMS, key=len, reverse=True)) + ")"
    "(" + "|".join(SELF_PARTICLES) + ")"
)

# ══════════════════════════════════════════════════════════
# ② 어미 — 「…습니다」를 「…다」로
# ══════════════════════════════════════════════════════════

#: 어미 바꾸기 표 (긴 것부터).
#: ★ **문장 끝에서만** 바꾼다. 가운데 것을 건드리면 뜻이 흔들릴 수 있다.
#: ⚠️ 여기 없는 모양은 **그냥 둔다.** 억지로 바꾸느니 원문이 낫다 —
#:   어색한 문장보다 «틀린 문장»이 훨씬 나쁘다.
ENDINGS: Final[tuple[tuple[str, str], ...]] = (
    ("하고 있습니다", "하고 있다"),
    ("되고 있습니다", "되고 있다"),
    ("이 아닙니다", "이 아니다"),
    ("있습니다", "있다"),
    ("없습니다", "없다"),
    ("습니다", "다"),          # 했습니다→했다 · 삼았습니다→삼았다
    ("합니다", "한다"),
    ("됩니다", "된다"),
    ("입니다", "이다"),
    ("립니다", "린다"),
    ("옵니다", "온다"),
    ("갑니다", "간다"),
    ("냅니다", "낸다"),
    ("깁니다", "긴다"),
    ("칩니다", "친다"),
    ("집니다", "진다"),
)

#: 「…하다」로 끝나는 **형용사** 어간.
#: ★ 왜 따로 두나 — 「합니다」의 평서형이 동사면 「한다」, 형용사면 「하다」다.
#:   구별을 안 하면 「예측이 불가능합니다」가 **「불가능한다」**가 된다 (실측으로 잡힘).
#:   공시에 자주 나오는 것만 담는다. 여기 없는 말은 동사로 보고 「한다」로 바꾼다 —
#:   공시 문장은 「판매합니다·운영합니다·추진합니다」처럼 동사가 압도적으로 많다.
#: ⚠️ 늘릴 때는 **실제 문장에 넣어 돌려볼 것.**
ADJECTIVE_STEMS: Final[tuple[str, ...]] = (
    "가능", "불가능", "필요", "불필요", "중요", "다양", "상이", "유사", "동일",
    "적정", "부적정", "충분", "불충분", "미미", "저조", "양호", "우수", "취약",
    "안정", "불안정", "명확", "불명확", "활발", "미흡", "원활", "특별", "광범위",
    "급격", "심각", "용이", "곤란", "적합", "부적합", "타당", "건전", "견고",
    "유효", "무효", "저렴", "고가", "복잡", "단순", "부족", "풍부", "적절",
)

#: 문장 끝으로 볼 글자 (어미 뒤에 올 수 있는 것).
SENTENCE_TAILS: Final[str] = ".!?"

# ══════════════════════════════════════════════════════════
# ③ 안 건드리는 것
# ══════════════════════════════════════════════════════════

#: 이 출처에서 온 문장은 **손대지 않는다.**
#: ★ 정본 규칙 — 공고 블록(5~8번)은 「원문 그대로 살린다」.
#:   지원자가 자소서에 그대로 옮겨 쓸 글이라 한 글자도 바꾸면 안 된다.
UNTOUCHED_CITES: Final[tuple[str, ...]] = ("공고",)

#: 회사 이름이 너무 짧으면 주어를 안 바꾼다.
#: ★ 한두 글자 이름을 문장에 넣으면 오히려 읽기 나빠진다.
MIN_COMPANY_NAME: Final[int] = 2
