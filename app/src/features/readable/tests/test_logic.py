"""공시 문투를 «읽히는 말»로 바꾸는 것을 못 박는다 (문제로그 P-107).

★ 왜 하나 — 사용자 지적: 「그냥 DART를 뜯어온 거라서, 이러면 그냥 DART를 직접 보지」.
  증권사 리포트는 공시를 3인칭으로 바꿔 쓴다 (조사 9건, 2026-08-16):
    공시  「당사는 … 하고 있습니다」  →  리포트 「두산인프라코어의 … 구성하고 있다」

★ **AI를 안 쓴다.** 정해 둔 낱말·어미를 바꿀 뿐이라 환각이 생길 자리가 없다.
  이 시험들이 지키는 것은 **「뜻이 안 바뀐다」**와 **「모르면 안 건드린다」** 둘이다.

⚠️ 이건 «표시용»이다. 원문은 부르는 쪽이 따로 보관해야 검증(W3)이 돈다.
"""

from __future__ import annotations

import pytest

from src.features.readable.logic import (
    display_name,
    replace_self,
    soften_ending,
    to_readable,
)


# ══════════════════════════════════════════════════════════
# ① 주어 — 「당사」를 회사 이름으로
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize(
    "원문, 기대",
    [
        ("당사는 공연을 제작한다", "하이브는 공연을 제작한다"),
        ("연결회사의 매출은 늘었다", "하이브의 매출은 늘었다"),
        ("본사가 직접 운영한다", "하이브가 직접 운영한다"),
        ("당해회사는 상장사다", "하이브는 상장사다"),
    ],
)
def test_1인칭_주어를_회사_이름으로_바꾼다(원문: str, 기대: str):
    assert replace_self(원문, "하이브") == 기대


def test_법인격_표기를_뗀다():
    """「(주)하이브는」보다 「하이브는」이 읽기 낫다."""
    assert replace_self("당사는 성장했다", "(주)하이브") == "하이브는 성장했다"


def test_조사는_그대로_둔다():
    """★ 조사를 다시 고르면 받침 규칙까지 따져야 하고, 틀리면 더 어색해진다."""
    assert replace_self("당사를 통해", "하이브") == "하이브를 통해"


# ── ★ 오거부·오적용 방지 ──────────────────────────────────


@pytest.mark.parametrize(
    "원문",
    [
        "당사자 간의 합의로 종결되었다",       # 「당사자」는 다른 말이다
        "연결회사채를 발행하였다",              # 「연결회사채」
        "상대회사와의 거래",                    # 앞에 한글이 붙어 있다
    ],
)
def test_비슷한_다른_말에는_안_걸린다(원문: str):
    """★ 여기가 깨지면 «뜻이 바뀐다» — 이 기능에서 가장 나쁜 실패다."""
    assert replace_self(원문, "하이브") == 원문


@pytest.mark.parametrize("이름", ["", " ", "A", "(주)"])
def test_이름이_너무_짧으면_안_바꾼다(이름: str):
    """한두 글자 이름을 넣으면 오히려 읽기 나빠진다."""
    assert replace_self("당사는 성장했다", 이름) == "당사는 성장했다"


# ══════════════════════════════════════════════════════════
# ② 어미 — 「…습니다」를 「…다」로
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize(
    "원문, 기대",
    [
        ("공연을 제작하고 있습니다.", "공연을 제작하고 있다."),
        ("매출이 늘었습니다.", "매출이 늘었다."),
        ("자료가 없습니다.", "자료가 없다."),
        ("재화를 판매합니다.", "재화를 판매한다."),
        ("계획입니다.", "계획이다."),
        ("성장이 예상됩니다.", "성장이 예상된다."),
    ],
)
def test_문장_끝_어미를_바꾼다(원문: str, 기대: str):
    assert soften_ending(원문) == 기대


# ── ★ 동사와 형용사를 가른다 ─────────────────────────────


@pytest.mark.parametrize(
    "원문, 기대",
    [
        ("예측이 불가능합니다.", "예측이 불가능하다."),      # 형용사
        ("추가 투자가 필요합니다.", "추가 투자가 필요하다."),  # 형용사
        ("경쟁이 심각합니다.", "경쟁이 심각하다."),           # 형용사
        ("사업을 운영합니다.", "사업을 운영한다."),           # 동사
        ("전략을 추진합니다.", "전략을 추진한다."),           # 동사
    ],
)
def test_형용사는_하다_동사는_한다(원문: str, 기대: str):
    """★ 안 가르면 「예측이 불가능합니다」가 **「불가능한다」**가 된다 — 실측으로 잡혔다."""
    assert soften_ending(원문) == 기대


# ── ★ 모르는 모양은 안 건드린다 ──────────────────────────


@pytest.mark.parametrize(
    "원문",
    [
        "매출이 늘었다.",                  # 이미 평서형
        "성장했음",                        # 명사형
        "2025년 매출 2조 6,499억원",        # 어미가 없다
        "",
    ],
)
def test_모르는_모양은_그대로_둔다(원문: str):
    """★ 억지로 바꾸느니 원문이 낫다 — 어색한 문장보다 «틀린 문장»이 훨씬 나쁘다."""
    assert soften_ending(원문) == 원문


def test_문장_가운데는_안_건드린다():
    """★ 가운데를 바꾸면 뜻이 흔들릴 수 있다. 끝에서만 바꾼다."""
    원문 = "매출이 늘었습니다만 영업이익은 줄었습니다."

    assert soften_ending(원문) == "매출이 늘었습니다만 영업이익은 줄었다."


# ══════════════════════════════════════════════════════════
# ③ 안 건드리는 것 — 공고 원문
# ══════════════════════════════════════════════════════════


def test_공고에서_온_문장은_손대지_않는다():
    """★ 정본이 「공고는 원문 그대로 살린다」고 못 박았다.

    지원자가 자소서에 **그대로 옮겨 쓸 글**이라 한 글자도 바꾸면 안 된다.
    """
    원문 = "당사는 신입사원을 모집합니다."

    assert to_readable(원문, "하이브", cite="공고") == 원문
    assert to_readable(원문, "하이브", cite="조각 2·수익인식") != 원문


# ══════════════════════════════════════════════════════════
# ④ 통째로 — 실제 공시 문장
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize(
    "원문, 기대",
    [
        (
            "당사는 소속 아티스트의 공연을 제작하고 있습니다.",
            "하이브는 소속 아티스트의 공연을 제작하고 있다.",
        ),
        (
            "연결회사는 국내외 유통사를 통해 재화를 판매합니다.",
            "하이브는 국내외 유통사를 통해 재화를 판매한다.",
        ),
        (
            "하이브는 멀티 레이블 전략을 통해서 성장을 지속시켜나갈 계획입니다.",
            "하이브는 멀티 레이블 전략을 통해서 성장을 지속시켜나갈 계획이다.",
        ),
    ],
)
def test_실제_공시_문장이_읽히게_바뀐다(원문: str, 기대: str):
    """★ 하이브 사업보고서에서 실제로 나온 문장이다."""
    assert to_readable(원문, "하이브") == 기대


def test_숫자와_사실은_한_글자도_안_바뀐다():
    """★ 이 기능이 절대 하면 안 되는 일 — 숫자·고유명사를 건드리는 것."""
    원문 = "2025년 당사의 연결기준 매출액은 2조 6,499억원으로 전년 대비 17% 성장했습니다."

    결과 = to_readable(원문, "하이브")

    assert "2조 6,499억원" in 결과
    assert "17%" in 결과
    assert "2025년" in 결과
    assert 결과 == "2025년 하이브의 연결기준 매출액은 2조 6,499억원으로 전년 대비 17% 성장했다."


def test_이름_다듬기():
    assert display_name("(주)하이브") == "하이브"
    assert display_name("주식회사 카카오") == "카카오"
