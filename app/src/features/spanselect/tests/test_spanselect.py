def test_후보_줄은_길어도_잘라서_보여준다():
    """보여주기만 자른다 — 보고서에 실리는 문장은 잘리지 않은 원문이다."""
    긴문장 = "가" * (SENTENCE_PREVIEW_CHARS + 50) + "."
    sent_map, lines, _excluded = number_sentences(
        {1: {"종류": "사업내용", "원문": 긴문장}}, 문장쪼개기
    )
    assert len(sent_map["1-1"][1]) == len(긴문장)          # 번호표에는 통째로 남는다
    assert lines[0].endswith("가" * 10)                     # 줄은 잘려 있다
    assert len(lines[0]) < len(긴문장)


