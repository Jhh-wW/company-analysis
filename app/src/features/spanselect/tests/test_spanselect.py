# ── 시험용 문장 쪼개기 ──────────────────────────────────
# 진짜로 쓰는 것은 1판 `run_pilot.split_sentences`다. 그것을 부르려면 `anthropic`이
# 깔려 있어야 해서 시험에서는 같은 규칙(마침표 기준·20자 미만 버림)의 간단판을 쓴다.
_MIN_CHARS = 20
_SPLIT = re.compile(r"(?<=[.!?])\s+")


def 문장쪼개기(text: str) -> list[str]:
    return [s.strip() for s in _SPLIT.split(text) if len(s.strip()) >= _MIN_CHARS]


