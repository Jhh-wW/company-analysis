"""못 쓰는 후보를 «AI에게 보여주기 전에» 거르는지 못 박는다 (문제로그 P-81).

★ 왜 필요한가 — 큰 모델은 **준 것 중에서** 고른다. 쓰레기를 주면 쓰레기를 고른다.
  모델을 격상한 뒤 실제 조사에서 이런 것들이 보고서 4번 칸에 실렸다:
    · 「…전 세계 18개국에 수출 노선을 확보했다....」  ← 네이버가 자른 토막
    · 「Find a provider News About Us … CLShop Webstore AMPS」 ← 홈페이지 메뉴 글자
    · 「(보도 · www.bokuennews.com) 사이노슈어 루트로닉, …」 ← 출처 표기가 앞에

★ 규칙은 **좁게** 잡는다. 「문장으로 안 끝나면 버린다」 같은 넓은 규칙은 홈페이지에서
  쓸 만한 문장까지 죽일 수 있는데, 1판 자료에 홈페이지 조각이 없어 **미리 잴 수 없다.**
  재지 못한 규칙은 넣지 않는다.
"""

from __future__ import annotations

import pytest

from src.features.spanselect.logic import is_unusable_candidate, number_sentences


def _쪼개기(text: str) -> list[str]:
    return [s.strip() for s in text.split("\n") if s.strip()]


# ══════════════════════════════════════════════════════════
# ① 버려야 하는 것
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize(
    "문장",
    [
        "사이노슈어 루트로닉의 세르프가 CE MDR 인증을 받으며 전 세계 18개국에 수출 노선을 확보했다....",
        "사이노슈어 루트로닉은 이번 인증을 바탕으로 독일, 오스트리아, 스위스 등 직영 판매망을 갖춘 국가와...",
        "글로벌머니익스프레스, 인도네시아 대상 한국 유학비·병원비 결…",
    ],
)
def test_잘린_토막은_후보에서_뺀다(문장: str):
    """네이버 뉴스가 본문을 잘라 보낸 자국 — 자소서에 그대로 못 쓴다."""
    assert is_unusable_candidate(문장)


def test_홈페이지_메뉴_글자는_후보에서_뺀다():
    """★ 실제로 보고서 4-3 칸에 실렸던 글자다."""
    메뉴 = (
        "Find a provider News About Us About Us Back Leadership Careers "
        "Contact Us CLShop Webstore AMPS"
    )

    assert is_unusable_candidate(메뉴)


# ══════════════════════════════════════════════════════════
# ② 살려야 하는 것 (오거부 안전핀)
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize(
    "문장",
    [
        "사이노슈어 루트로닉이 차세대 RF 기기 세르프가 유럽 CE MDR 인증에 앞서 18개국 허가를 완료했다고 전했다.",
        "토스씨엑스가 상담 직무를 단순 고객 응대가 아닌 서비스 개선과 연결되는 전문 역할로 확장하는 데 힘을 싣고 있다.",
        "2025년 연결기준 매출액 5,363억원, 영업이익 2,144억원의 실적을 달성하였습니다.",
        "우리엔은 2019년 동물병원 전용 CT와 치과용 파노라마 장비를 출시했다",
        "회사는 AI·MTS 개발을 추진 중",          # 종결부호가 없어도 한글 문장이면 살린다
    ],
)
def test_쓸_만한_문장은_안_버린다(문장: str):
    """★ 여기가 깨지면 4번 칸이 다시 빈다 — 걸러내기가 과했다는 뜻이다."""
    assert not is_unusable_candidate(문장)


def test_문장_중간의_말줄임표는_버리는_이유가_아니다():
    """잘림 자국은 «끝»에 있다. 중간의 「…」는 원문 그대로일 수 있다."""
    문장 = "파마리서치, 하반기 리쥬란 교육·학술 프로그램 확대…전국 현장 접점을 넓힌다."

    assert not is_unusable_candidate(문장)


# ══════════════════════════════════════════════════════════
# ③ 출처 표기 — 버리지 않고 앞머리만 뗀다
# ══════════════════════════════════════════════════════════


def test_기사_제목의_출처_표기를_뗀다():
    """날짜·주소는 출처 목록에 이미 있다 — 문장에 남기면 그대로 못 쓴다.

    ★ 제목줄 자체는 «온전한 문장»이라 버리지 않는다. 실측상 잘린 토막을 걸러내면
      남는 후보의 상당수가 이 제목줄이다 — 이것까지 버리면 4번 칸이 다시 빈다.
    """
    조각 = {
        1: {
            "종류": "뉴스",
            "원문": "(2026-07-16 보도 · www.bokuennews.com) 사이노슈어 루트로닉, 유럽 CE MDR 인증 획득.",
        }
    }

    sent_map, lines, excluded = number_sentences(조각, _쪼개기)

    assert excluded == 0, "제목줄을 버리면 안 된다"
    문장 = sent_map["1-1"][1]
    assert not 문장.startswith("("), f"출처 표기가 남았습니다: {문장}"
    assert "보도 ·" not in 문장
    assert 문장.startswith("사이노슈어 루트로닉,")


def test_걸러낸_문장은_번호표에_아예_없다():
    """★ 번호표에 없으면 AI가 부를 수 없다 — 「부탁」이 아니라 «구조»로 막는다."""
    조각 = {
        1: {
            "종류": "뉴스",
            "원문": "회사가 유럽 인증을 받았다.\n회사는 이번 인증을 바탕으로 독일, 오스트리아...",
        }
    }

    sent_map, lines, excluded = number_sentences(조각, _쪼개기)

    assert excluded == 1
    assert "1-2" not in sent_map
    assert not any("독일, 오스트리아" in line for line in lines)
