"""지원 맥락별 «열쇠 링크»에 쓰는 값.

★ 왜 만드나 — 포트폴리오를 본 인사팀이 **로그인 없이** 이 도구를 직접 눌러보게 하려는 것.
  계정을 주면 로그인이 귀찮아 아무도 안 쓰고, 아무나 열어두면 돈이 무제한으로 샌다.
  그 사이를 «회사마다 다른 링크»로 푼다.

★ 이 링크가 하는 일 세 가지
  ① 로그인 없이 쓰게 해준다
  ② **처음 연결한 보고서를 미리 보여 주고** 다른 회사도 이어서 조사하게 한다
  ③ **링크마다 하루 예산을 따로 센다** — 한 회사 인사팀이 다 써도 다른 링크는 멀쩡하다
"""

