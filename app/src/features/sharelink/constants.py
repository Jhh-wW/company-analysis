DEFAULT_LINK_MAX_AGE_DAYS: Final[int] = 90

#: 만료일 열(``share_links.expires_at``)이 생기기 «전»에 발급된 링크의 수명.
#: ★ 왜 남겨 두나 — 기본값을 90일로 올릴 때 이미 뿌려 둔 링크까지 30일 더
#:   열리면, 그건 아무도 결정한 적 없는 노출 연장이다. 저장소를 준비할 때
#:   기존 행의 만료일을 «이 값으로» 계산해 표에 적어 굳힌다(`store.ensure_schema`).
LEGACY_LINK_MAX_AGE_DAYS: Final[int] = 60

ENV_LINK_MAX_AGE_DAYS: Final[str] = "SHARE_LINK_MAX_AGE_DAYS"
MAX_LINK_MAX_AGE_DAYS: Final[int] = 3650

#: 관리자가 «한 번에» 미룰 수 있는 만료일의 상한(오늘부터의 일수).
#: ★ 상한이 없으면 실수로 2099년을 넣어도 그대로 저장된다. 연장은 여러 번
#:   할 수 있으므로, 한 번의 폭을 기본 수명과 같게 묶어 두는 편이 안전하다.
MAX_LINK_EXTENSION_DAYS: Final[int] = DEFAULT_LINK_MAX_AGE_DAYS

#: 발급일부터 세는 링크의 **총 수명 상한**(일). 미루기를 몇 번 하든 이 날을 넘지
#: 못한다.
#: ★ 1회 상한(``MAX_LINK_EXTENSION_DAYS``)과 막는 위험이 다르다 —
#:   1회 상한은 「실수로 2099년을 넣는 것」을, 총 상한은 「조금씩 계속 미뤄
#:   사실상 영구 링크가 되는 것」을 막는다. QR은 한 번 뿌리면 회수할 수 없다.
MAX_LINK_TOTAL_AGE_DAYS: Final[int] = 365

#: 연장 사유로 받을 글자 수 상한. 사유는 «나중의 나»를 위한 기록이라 필수다.
LINK_ADJUSTMENT_REASON_MAX_CHARS: Final[int] = 200

