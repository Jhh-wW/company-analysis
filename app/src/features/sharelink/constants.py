#: 발급 링크가 자동으로 닫힐 때까지의 기본 일수. 수동 ``닫기``는 그대로 즉시 적용된다.
#: ★ 60일 → **90일**. 채용 일정이 두 달을 넘는 경우가
#:   흔하고, QR은 한 번 뿌리면 회수할 수 없어 「기간이 모자라 다시 뿌리는」 쪽이
#:   「조금 더 오래 열어 두는」 쪽보다 노출이 크기 때문이다.
#: ★ 이 값은 «새로 발급하는» 링크에만 걸린다. 이미 저장된 링크의 만료일은
