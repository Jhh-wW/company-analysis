#: ★★ 손님을 «네 갈래»로 나눠 각각 다른 상한을 건다 (사용자 결정).
#:   같은 상한을 다 걸면, 포트폴리오용 링크 하나가 친구들 몫까지 먹어버린다.
#:
#:   | 갈래        | 누구             | 하루 상한 | 그 밖의 상한 | 왜 이 값인가                       |
#:   |------------|------------------|----------|------------|-----------------------------------|
#:   | 관리자      | 나 (개발자)       | 5,000원  | 없음        | 개발·검증에 쓰는 몫. 실수로 새도 여기서 멈춘다 |
#:   | 로그인 사용자 | 친구들            | 3,000원  | 성공 보고서 3건/일 | 실패 반복과 성공 남용을 각각 제한 |
#:   | 열쇠 링크    | LINK 방문자         | 3,000원  | **수명 전체 누적 3,000원** | 링크 하나에 배정된 여러 조사 합계 |
#:   | 모르는 손님   | 그냥 들어온 사람   | **0원**  | 없음        | 데모만. 진짜 조사는 아예 안 준다      |
#:
#:   ★ LINK만 «하루»와 «누적» 두 줄이다 (사용자 결정). 하루 상한만
#:     두면 링크 수명(기본 90일) 동안 매일 되살아나 최악 노출이 3,000 × 90이었다.


#: **열쇠 링크 하나가** 하루에 쓸 수 있는 AI 비용(원).
#: ★ 「전체 합계」가 아니라 «링크당»이다 — 한 회사 인사팀이 다 써도
#:   다른 LINK는 멀쩡히 돈다. 지원회사·지원직무는 통장을 나누는 기준이 아니다.
#: ⚠️ **전체 상한은 두지 않기로 했다 (사용자 결정).** 그러므로
#:   **호출 전 비용 입장 기준 합계 = 3,000원 × 살아 있는 링크 수**다.
#:   링크가 20개면 새 호출을 허용할지 판단하는 기준 합계가 60,000원이다.
#:   실제 청구액은 provider 토큰 집계·가격·환율과 마지막 허용 호출의 차이 때문에
#:   이 합계를 넘을 수 있으므로 절대 지출 상한이라고 부르지 않는다.
#:   → 링크를 «몇 개나» 뿌렸는지가 비용 노출 규모를 정한다. 관리 화면에서 확인할 것.
#: ★ 이 값은 «하루»만 센다. 링크 수명 전체는 아래 ``LINK_TOTAL_BUDGET_KRW``가 막는다.
PER_LINK_DAILY_BUDGET_KRW: Final[float] = 3000.0

#: **열쇠 링크 하나가 수명 전체에 걸쳐** 쓸 수 있는 AI 비용(원).
#: ★ 왜 하루 상한만으로 부족한가 — 하루 상한은 자정마다 되살아난다. 링크는 기본
#:   90일을 사니까, 하루 3,000원만 두면 링크 하나의 최악 노출이 27만 원이었다.
#:   누적 상한은 그 곱셈을 끊어 **링크 하나 = 최대 3,000원**으로 총액을 닫는다.
#: ★ 둘 다 적용한다 — 하루 상한은 봇·장난의 «속도»를, 누적 상한은 «총액»을 막는다.
#:   둘 중 하나라도 닿으면 새 조사를 시작하지 않는다.
#: ★ 누적 사용액 = 그 링크의 종결된 실행 실측 원가 합(``share_link_run_history``의
#:   ``internal_ai_cost_krw``) + 지금 진행 중인 예약액(비용 원장의 ACTIVE 예약).
#:   진행 중 예약을 빼면 조사가 도는 동안 새 조사가 계속 들어와 천장을 넘는다.
#: ⚠️ 이 값도 절대 청구 상한은 아니다. 마지막으로 허용된 호출의 실측이 예약보다
#:   클 수 있어 소진 시점의 실제 원가는 이 값을 조금 넘을 수 있다.
#: ★ 링크마다 다른 값을 주고 싶으면 ``share_links.total_budget_krw``에 적는다.
#:   비어 있으면(기존 링크 전부) 이 기본값을 쓴다.
LINK_TOTAL_BUDGET_KRW: Final[float] = 3000.0

#: **초대한 친구 한 사람**이 하루에 예약할 수 있는 AI 비용(원).
#:
#: 성공 보고서 3건 제한만으로는 실패한 조사를 막지 못한다. 회사 찾기·회사 확인·OCR처럼
#: 보고서가 완성되기 전에 돈을 쓰는 단계가 계속 실패하면 성공 건수는 0인 채 비용만
#: 반복해서 나갈 수 있다. 따라서 MEMBER에는 다음 두 안전장치를 함께 둔다.
#:
#: * 비용 입장 상한 3,000원 — 실패를 포함한 모든 유료 단계를 멈춘다.
#: * 성공 보고서 3건 — 값싼 캐시 결과만 반복해서 받는 사용량도 제한한다.
#:
#: 이 값은 실제 카드 청구액의 절대 상한이 아니라, 보수적으로 잡은 예약 비용을 기준으로
#: 새 호출을 허용할지 정하는 입장 상한이다.
PER_USER_DAILY_BUDGET_KRW: Final[float] = 3000.0

#: **관리자(나)**가 하루에 쓸 수 있는 AI 비용(원).
#: ★ 왜 관리자에게도 상한을 두나 — 「내 돈이니까 무제한」이 가장 위험하다.
#:   코드 실수로 반복 호출이 돌면 밤새 수만 원이 나갈 수 있다. 상한은 «나»를 위한 것이기도 하다.
ADMIN_DAILY_BUDGET_KRW: Final[float] = 5000.0

#: **모르는 손님**(로그인도 열쇠도 없는 사람)의 하루 상한.
#: ★ **0원 = 진짜 조사를 아예 안 준다** (사용자 결정).
#:   현재 1개 canonical 데모 회사로 제품 흐름은 확인할 수 있다.
#:   데모 수와 무관하게 익명 사용자의 실제 provider 호출은 허용하지 않는다.
#:   인터넷에 공개된 상태에서 검색엔진 봇·장난에 돈이 새는 길을 **완전히** 막는다.
PUBLIC_DAILY_BUDGET_KRW: Final[float] = 0.0

#: 열쇠가 없는 손님(그냥 주소로 들어온 사람)을 묶어 셀 이름.
#: ★ 이 사람들도 «하나의 통장»으로 묶는다 — 안 그러면 상한을 걸 대상이 없어진다.
PUBLIC_BUCKET: Final[str] = "(열쇠 없음)"

#: 로그인한 사람의 통장 이름 앞에 붙이는 표시.
#: ★ 열쇠(16진수)와 «절대 겹치지 않는» 글자를 쓴다 — 겹치면 남의 통장을 쓰게 된다.
USER_BUCKET_PREFIX: Final[str] = "user:"

#: 모르는 손님이 진짜 조사를 누르려 할 때 보여줄 말.
#: ★ 「아래 회사들은 …」이라고 말하지 않는다 — 이 말이 나가는 화면에 **회사 목록이
#:   없다**(첫 화면의 예시 칩은 데모 모드 전용). 화면에 없는 것을 가리키면 손님은
#:   자기가 못 찾는 줄 알고 헤맨다. 「그래도 되는 것」은 화면 틀이 따로 말한다.
PUBLIC_NOT_ALLOWED_MESSAGE: Final[str] = (
    "새 조사는 로그인하신 분이나 초대 링크로 들어오신 분만 하실 수 있습니다."
)

