"""돈과 횟수를 막는 값 (배포 안전 §1 — 문제로그 P-92).

★ 왜 필요한가 — `/run`에는 로그인도, 횟수 제한도, 예산 상한도 «없었다».
  진짜 조사 모드로 인터넷에 올리는 순간, 아무나 회사 이름만 바꿔가며
  건당 82~182원을 **무제한으로** 쓰게 만들 수 있다.
  캐시는 못 막는다 — 회사·직무를 조금씩 바꾸면 매번 새 조사가 된다.

★ 「계정을 주면 상한을 걸 수 있다」는 오해다. 상한은 **서버가** 거는 것이고,
  계정은 «누가 썼는지»를 알려줄 뿐 돈을 막아주지 않는다.
"""

from __future__ import annotations

from typing import Final

# ══════════════════════════════════════════════════════════
# 하루 예산
# ══════════════════════════════════════════════════════════

#: 하루에 쓸 수 있는 AI 비용 상한(원). 넘으면 진짜 조사를 «거절»한다.
#: ★ 3,000원 = 실측 평균(약 120원) 기준 **하루 25건**쯤이다.
#:   포트폴리오를 본 인사팀이 호기심에 여러 회사를 눌러봐도 감당되는 선이고,
#:   장난이나 자동 프로그램이 붙어도 하루 손실이 3,000원에서 멈춘다.
#: ⚠️ 이 값을 올릴 때는 «잃어도 되는 돈»인지 먼저 생각할 것.
DAILY_BUDGET_KRW: Final[float] = 3000.0

#: 예산이 다 됐을 때 사용자에게 보여줄 말.
#: ★ 「고장」이 아니라 «오늘 몫을 다 썼다»는 뜻임을 분명히 한다 —
#:   고장으로 오해하면 이 도구가 못 쓰는 물건으로 보인다.
BUDGET_EXHAUSTED_MESSAGE: Final[str] = (
    "오늘 준비된 조사 횟수를 모두 사용했습니다. "
    "내일 다시 시도해 주세요 — 저장된 보고서는 그대로 보실 수 있습니다."
)

# ══════════════════════════════════════════════════════════
# 요청 횟수 (한 사람이 몰아치는 것을 막는다)
# ══════════════════════════════════════════════════════════

#: 횟수를 세는 시간 창(초).
RATE_WINDOW_SEC: Final[int] = 600          # 10분

#: 그 시간 창 안에 한 곳(IP)이 시작할 수 있는 조사 수.
#: ★ 사람이 쓰는 속도로는 넉넉하다 — 조사 한 건이 1~2분 걸린다.
#:   자동 프로그램만 걸린다.
RATE_MAX_RUNS: Final[int] = 5

#: 횟수 제한에 걸렸을 때 보여줄 말.
RATE_LIMITED_MESSAGE: Final[str] = (
    "잠시 후 다시 시도해 주세요. "
    "짧은 시간에 너무 많이 요청하면 잠깐 쉬어갑니다."
)

# ══════════════════════════════════════════════════════════
# 동시 실행 (메모리와 예산 «넘침»을 같이 막는다)
# ══════════════════════════════════════════════════════════

#: 서버 전체에서 동시에 돌 수 있는 조사 수 (2026-08-17 사용자 결정).
#: ★ 예산 검사는 «시작 전»에 하고 비용은 «끝난 뒤» 더해진다. 그 사이에
#:   여러 건이 동시에 통과하면 상한을 조금 넘길 수 있다(경합).
#:   같은 비용 통장의 넘침 폭은 아래의 사용자·링크별 상한으로 더 작게 묶는다.
MAX_CONCURRENT_RUNS: Final[int] = 5

#: 같은 로그인 계정은 한 자리만 쓴다. «로그인 사용자 5명»은 서로 다른
#: 계정 다섯 개가 한 건씩 쓰는 뜻이다 (2026-08-17 사용자 결정).
MAX_CONCURRENT_PER_USER: Final[int] = 1

#: 같은 초대 링크를 함께 쓰는 인사팀은 세 명까지 동시에 조사한다.
#: 링크 하나는 같은 비용 통장을 쓰므로 전역 5건보다 작게 둔다.
MAX_CONCURRENT_PER_LINK: Final[int] = 3

#: 동시 실행이 꽉 찼을 때 보여줄 말.
BUSY_MESSAGE: Final[str] = (
    "지금 다른 조사가 진행 중입니다. 1~2분 뒤에 다시 눌러 주세요."
)

# ══════════════════════════════════════════════════════════
# 메모리 청소 (문제로그 P-92-b)
# ══════════════════════════════════════════════════════════

#: 끝난 조사를 메모리에 남겨 두는 시간(초). 넘으면 치운다.
#: ★ 안 치우면 `_JOBS`가 서버가 죽을 때까지 쌓인다 — 데모(공짜)에서도 마찬가지다.
JOB_KEEP_SEC: Final[int] = 3600            # 1시간

#: 메모리에 둘 수 있는 조사의 최대 개수. 넘으면 «오래된 것부터» 치운다.
#: ★ 시간 기준만 두면, 1시간 안에 몰아치는 경우를 못 막는다. 두 기준을 같이 건다.
JOB_MAX_KEPT: Final[int] = 200

# ══════════════════════════════════════════════════════════
# 비용 원장 — 유료 단계를 서로 겹치지 않게 가르는 이름
# ══════════════════════════════════════════════════════════

#: 회사 이름을 DART 법인에 맞추는 AI 단계.
SPEND_PHASE_IDENTIFY: Final[str] = "회사_식별"
#: 채용공고 사진에서 글자를 읽는 AI 단계.
SPEND_PHASE_OCR: Final[str] = "이미지_OCR"
#: 확인 뒤 판정·수집·생성·검증을 하는 본조사 단계.
SPEND_PHASE_PIPELINE: Final[str] = "본조사"
SPEND_PHASES: Final[tuple[str, ...]] = (
    SPEND_PHASE_IDENTIFY,
    SPEND_PHASE_OCR,
    SPEND_PHASE_PIPELINE,
)
