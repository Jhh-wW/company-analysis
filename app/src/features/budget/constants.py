#: 같은 로그인 계정이 «동시에» 쥘 수 있는 자리 수 (제품 결정).
#: ★ 왜 1이 아니라 2인가 — 한 사람이 회사를 검색해 두고 다른 창에서 앞서
#:   만들어 둔 결과를 여는 것은 흔한 동작인데, 1이면 그 두 번째 동작이
#:   「다른 조사가 진행 중」으로 막혔다. 하루 비용 상한은 그대로라
#:   자리를 하나 더 준다고 쓸 수 있는 돈이 늘지는 않는다.
MAX_CONCURRENT_PER_USER: Final[int] = 2

#: 초대 링크에서 «방문자 한 사람»이 동시에 쥘 수 있는 자리 수 (제품 결정).
#: ★ 열쇠가 아니라 «사람»마다 센다. 링크 하나를 인사팀 여러 분이 나눠 쓰므로,
#:   열쇠로만 세면 한 분이 도는 동안 나머지가 전부 막혔다. 사람은 방문자 쿠키
#:   (``VISITOR_COOKIE_NAME``)로 구분하고, 쿠키가 없으면 예전처럼 링크 하나가
#:   한 자리를 쓴다.
#: ★ 한 사람이 두 건을 동시에 열 이유는 없다 — 링크 통장은 여럿이 나눠 쓰는
#:   돈이라, 한 사람이 앞서 두 자리를 잡으면 그만큼 뒷사람 몫이 준다.
MAX_CONCURRENT_PER_LINK: Final[int] = 1

#: 초대 링크 «하나 전체»가 동시에 쥘 수 있는 자리 수 (제품 결정).
#: ★ 왜 상한이 또 필요한가 — 방문자마다 한 자리를 주면 링크 하나가 서버 자리를
#:   전부 먹을 수 있다. 다른 링크와 로그인 사용자 몫을 남겨 두려면 링크 쪽에도
#:   천장이 있어야 한다.
#: ⚠️ **이 값은 「다섯 건이 다 끝난다」는 약속이 아니다.** 비용 통장은 지금도
#:   링크 단위라, 본조사 한 건이 ``PAID_PHASE_PROVIDER_BUDGET_KRW``의 본조사
#:   예약액만큼 잡는다. 링크 누적 상한(3,000원)에 먼저 닿으면 자리가 남아 있어도
#:   예산 문구로 막힌다 — 그때 나가는 말은 「다른 조사가 진행 중」이 아니다.
#: ★ 서버 전체 상한(``MAX_CONCURRENT_RUNS``)을 넘지 않아야 한다. 넘으면 링크
#:   상한이 아무것도 막지 못하는 죽은 값이 된다.
