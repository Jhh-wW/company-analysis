#: ``MAX_CONCURRENT_RUNS``의 정본은 여러 feature가 함께 쓰므로 ``core``에 있다.
#: 같은 통장의 호출 전 예상비용은 SQLite에서 원자 예약해 동시 경쟁을 닫는다.
