"""보고서 링크를 «공유해도 안전하게» 만드는 값과 헤더 (문제로그 P-93).

★ 정한 것 (사용자 결정) — 보고서 링크는 **링크를 아는 사람 누구나** 본다.
  포트폴리오를 본 인사팀이 동료에게 링크를 넘기는 것이 «오히려 원하는 일»이고,
  내용도 공개된 공시·뉴스라 민감도가 낮다.
  ⚠️ 공고 원문은 애초에 저장되지 않는다 (정본 S2) — 링크로도 새어나갈 것이 없다.
  ⚠️ 이 보고서 주소는 회사별 열쇠(`/k/...`)와 독립적이다. 열쇠가 닫혀도 이미 받은
    보고서 주소 자체는 보고서를 만든 날부터 60일 동안 열리고, 그날 정확히 닫힌다.

★ 그래서 「잠그기」 대신 **새어나갈 «길»을 막는다:**
  ① 주소를 추측할 수 없게 (128비트)
  ② 검색엔진에 안 걸리게
  ③ 외부 사이트로 주소가 «자동 전달»되지 않게 (리퍼러)
  ④ 로그인 상태에 따라 달라진 화면을 브라우저·중간 서버가 보관하지 않게 (캐시)
"""

from __future__ import annotations

from typing import Final

#: 보고서 주소에 쓸 무작위 글자 수 (16진수). 32자리 = **128비트**.
#: ★ 예전에는 12자리(48비트)였다. 48비트도 찍어 맞히긴 어렵지만,
#:   주소가 «공개 링크»가 되는 이상 여유를 크게 두는 편이 싸게 먹힌다.
#:   32자리로 늘리는 비용은 사실상 0이다.
REPORT_ID_HEX_CHARS: Final[int] = 32

#: 검색엔진이 보고서를 긁어가지 못하게 하는 헤더.
#: ★ 이게 없으면 누군가 링크를 블로그에 올리는 순간 «검색에 뜨는» 문서가 된다.
NOINDEX_HEADER: Final[dict[str, str]] = {
    "X-Robots-Tag": "noindex, nofollow, noarchive",
}

#: 보고서 화면에서 «다른 사이트로 나갈 때» 주소를 안 알려주는 헤더.
#: ★ 왜 필요한가 — 보고서 안의 뉴스 링크를 누르면, 그 뉴스 사이트에
#:   「어느 주소에서 왔는지」(= 보고서 주소)가 자동으로 전달된다.
#:   그 기록을 통해 제3자가 링크를 알게 되는 것이 가장 현실적인 유출 경로다.
NO_REFERRER_HEADER: Final[dict[str, str]] = {
    "Referrer-Policy": "no-referrer",
}

#: 보고서·내려받기 응답에 같이 붙일 헤더 전부.
SHARED_LINK_HEADERS: Final[dict[str, str]] = {
    **NOINDEX_HEADER,
    **NO_REFERRER_HEADER,
    # 로그인한 관리자가 같은 공개 주소를 보면 이메일·CSRF가 화면에 추가될 수 있다.
    # 브라우저나 중간 캐시가 그 개인화 응답을 다른 사람에게 재사용하지 못하게 한다.
    "Cache-Control": "private, no-store",
    "Pragma": "no-cache",
    "Vary": "Cookie",
}

# ══════════════════════════════════════════════════════════
# 링크 수명 — 두 달 뒤 저절로 닫힌다
# ══════════════════════════════════════════════════════════

#: 보고서 링크가 살아 있는 기간(일). 생성일부터 정확히 이 날짜가 되면 닫힌다.
#: ★ 두 가지를 같이 해결한다:
#:   ① **보안** — 링크가 어딘가에 남아도 영원히 열리지는 않는다.
#:      공유를 허용한 대신, 「언제까지」를 정해 위험이 무한히 쌓이지 않게 한다.
#:   ② **정직함** — 조사 내용은 시간이 지나면 낡는다. 반년 전 재무·뉴스를
#:      「지금 이 회사」인 것처럼 보여주면 그게 더 나쁘다.
#: ⚠️ 지우는 게 아니다. **보여주기를 멈출 뿐** 이력·저장소는 그대로 남는다.
#: ⚠️ 회사별 열쇠 링크의 생성일·삭제 여부와는 별개다. 보고서 URL을 이미 받은 사람은
#:    이 보고서 자체의 생성일부터 아래 기간 동안 볼 수 있다는 기존 공개 정책을 지킨다.
REPORT_LINK_MAX_AGE_DAYS: Final[int] = 60

#: 만료된 링크에 보여줄 말.
#: ★ 「없는 보고서」라고 하지 않는다 — 있었는데 «기간이 지난» 것이고,
#:   그 둘은 사용자에게 완전히 다른 뜻이다 (없다=내가 잘못 왔나, 지났다=아 그렇구나).
LINK_EXPIRED_MESSAGE: Final[str] = (
    "이 보고서 링크는 만들어진 지 두 달이 지나 더 이상 열리지 않습니다. "
    "조사 내용은 시간이 지나면 낡기 때문에, 오래된 자료를 지금 것처럼 "
    "보여드리지 않으려고 기간을 두었습니다."
)
