"""작가 AI를 못 박는다.

★ 여기서 지키는 것은 셋이다.
  ① **근거를 가리키지 못하는 문장은 못 나간다** — 대조 못 하면 지어낸 것과 같다.
  ② **검사가 죽으면 전부 버린다** — 검사 없이 내보내면 「검증됐다고 표시된 거짓말」이 된다.
  ③ **공고 블록에는 손대지 않는다** — 자소서에 그대로 옮겨 쓸 글이다.
"""

from __future__ import annotations

from typing import Any

import pytest

from src.features.writer.constants import WRITTEN_CELLS
from src.features.writer.logic import (
    Evidence,
    Sentence,
    apply_written,
    build_prompt,
    collect_evidence,
    to_cited_lines,
    write_with_ai,
)


def _근거() -> dict[str, list[Evidence]]:
    return {
        "4-3": [
            Evidence("4-3-1", "하이브가 추구하는 전략은 음악과 기술의 접목이다.", "조각 10·신규사업전망"),
            Evidence("4-3-2", "위버스에 AI를 적용하는 작업이 진행 중이다.", "조각 14·뉴스"),
        ]
    }


# ══════════════════════════════════════════════════════════
# ① 근거 모으기
# ══════════════════════════════════════════════════════════


def test_칸별_원문에_근거_번호를_붙인다():
    근거 = collect_evidence({"4-3": [("가나다", "조각 10"), ("라마바", "조각 14·뉴스")]})

    assert [e.sid for e in 근거["4-3"]] == ["4-3-1", "4-3-2"]
    assert 근거["4-3"][0].text == "가나다"


def test_공고_블록은_작가에게_안_맡긴다():
    """★ 정본이 「공고는 원문 그대로 살린다」고 못 박았다.

    지원자가 자소서에 **그대로 옮겨 쓸 글**이라 작가가 손대면 안 된다.
    """
    for 공고칸 in ("5", "6", "7", "8"):
        assert 공고칸 not in WRITTEN_CELLS

    근거 = collect_evidence({"7": [("영어 커뮤니케이션이 원활한 분", "공고")]})

    assert 근거 == {}


def test_빈_문장은_근거로_안_센다():
    assert collect_evidence({"4-3": [("  ", "조각 1")]}) == {}


def test_출처가_빈_문장은_작가_근거로_안_센다():
    """표시용 사실 문장 뒤에 실제 출처를 못 붙이는 입력은 처음부터 맡기지 않는다."""
    assert collect_evidence({"4-3": [("전략 문장", "")]}) == {}


def test_기사_근거를_알아본다():
    """★ 「공시가 말한 방향 + 기사가 말한 증거」로 이으라고 알려 줘야 한다."""
    근거 = collect_evidence({"4-3": [("가", "조각 10·신규사업전망"), ("나", "조각 14·뉴스")]})

    assert 근거["4-3"][0].is_news is False
    assert 근거["4-3"][1].is_news is True


