def test_쓴_문장과_근거_번호를_받는다():
    쓴것, 버림 = apply_written(
        {"칸": [{"칸번호": "4-3", "문장들": [
            {"글": "하이브는 음악과 기술을 접목하려 한다.", "근거": "4-3-1"}
        ]}]},
        _근거(),
    )

    assert 쓴것["4-3"][0].text == "하이브는 음악과 기술을 접목하려 한다."
    assert 쓴것["4-3"][0].sid == "4-3-1"
    assert sum(버림.values()) == 0


@pytest.mark.parametrize(
    "답, 사유",
    [
        ({"칸": [{"칸번호": "4-3", "문장들": [{"글": "가", "근거": "없는번호"}]}]}, "모르는근거"),
        ({"칸": [{"칸번호": "9", "문장들": [{"글": "가", "근거": "4-3-1"}]}]}, "모르는근거"),
        ({"칸": [{"칸번호": "4-3", "문장들": [{"글": "  ", "근거": "4-3-1"}]}]}, "빈글"),
    ],
)
def test_근거를_못_가리키는_문장은_버린다(답: dict[str, Any], 사유: str):
    """★★ 대조할 수 없는 문장은 **지어낸 것과 구별되지 않는다.**"""
    쓴것, 버림 = apply_written(답, _근거())

    assert 쓴것 == {}
    assert 버림[사유] >= 1


def test_칸당_문장_상한을_지킨다():
    답 = {"칸": [{"칸번호": "4-3", "문장들": [
        {"글": f"문장{i}", "근거": "4-3-1"} for i in range(10)
    ]}]}

    쓴것, 버림 = apply_written(답, _근거(), limit=3)

    assert len(쓴것["4-3"]) == 3
    assert 버림["상한초과"] == 7


def test_다른_칸의_근거번호를_대면_버린다():
    """전역에 실재하는 번호여도 해당 항목의 근거가 아니면 배치 오류다."""
    근거 = {
        "1": [Evidence("1-1", "사업 문장", "조각 1")],
        "4-3": [Evidence("4-3-1", "전략 문장", "조각 2")],
    }
    답 = {
        "칸": [
            {
                "칸번호": "1",
                "문장들": [{"글": "전략을 사업으로 잘못 놓았다.", "근거": "4-3-1"}],
            }
        ]
    }

    쓴것, 버림 = apply_written(답, 근거)

    assert 쓴것 == {}
    assert 버림["모르는근거"] == 1


def test_AI가_실패하면_아무것도_안_쓴다():
    """★ 빈손으로 돌아가면 부르는 쪽이 «원문 나열»로 되돌린다."""
    쓴것, 버림 = apply_written(None, _근거())

    assert 쓴것 == {}


def test_근거가_없으면_AI를_안_부른다():
    """★ 돈이 나가는 일이다."""
    불렀나 = []

    쓴것, 기록 = write_with_ai(
        lambda p, s: (불렀나.append(1), ({}, {}))[1],
        company="하이브", job="매니지먼트", evidence={},
    )

    assert 쓴것 == {}
    assert 불렀나 == []


def test_통째로_돌린다():
    def ask(prompt, schema):
        assert "4-3-1" in prompt
        return {"칸": [{"칸번호": "4-3", "문장들": [
            {"글": "하이브는 음악과 기술을 접목하려 한다.", "근거": "4-3-1"},
            {"글": "실제로 위버스에 AI를 적용하는 작업이 진행 중이다.", "근거": "4-3-2"},
        ]}]}, {"in": 900, "out": 120}

    쓴것, 기록 = write_with_ai(
        ask, company="하이브", job="매니지먼트", evidence=_근거()
    )

    assert len(쓴것["4-3"]) == 2
    assert 기록["쓴문장"] == 2
    assert 기록["usage"]["in"] == 900


