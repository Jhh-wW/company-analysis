# ② 지시문
# ══════════════════════════════════════════════════════════


def test_지시문이_지어내기를_금지한다():
    프롬프트 = build_prompt("하이브", "매니지먼트", _근거())

    assert "근거에 없는 사실을 단 한 글자도 더하지 마라" in 프롬프트
    assert "그 문장은 버려진다" in 프롬프트
    assert "문장마다 근거 번호를 하나씩 반드시 달아라" in 프롬프트


def test_지시문이_공시와_기사를_구분해_보여준다():
    """★ 작가가 「방향 + 증거」로 이으려면 어느 것이 기사인지 알아야 한다."""
    프롬프트 = build_prompt("하이브", "매니지먼트", _근거())

    assert "[공시·홈페이지]" in 프롬프트
    assert "[기사]" in 프롬프트
    assert "(4-3-1)" in 프롬프트


def test_지시문이_말투를_정한다():
    """★ 사용자 선택: 말투는 «작가가 흡수»한다."""
    프롬프트 = build_prompt("하이브", "매니지먼트", _근거())

    assert "평서형" in 프롬프트
    assert "「당사」" in 프롬프트


def test_지시문이_억지로_늘리지_말라고_한다():
    프롬프트 = build_prompt("하이브", "매니지먼트", _근거())

    assert "억지로 늘리지 마라" in 프롬프트
    assert "비워도 된다" in 프롬프트


