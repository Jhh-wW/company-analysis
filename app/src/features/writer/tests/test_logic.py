def test_검증된_문장의_내부번호를_실제출처로_되돌린다():
    """내부 번호를 버리거나 그대로 내지 않고 사용자가 찾을 출처로 바꾼다."""
    문장 = [Sentence("하이브는 음악과 기술을 접목하고 있다.", "4-3-1")]

    assert to_cited_lines(문장, _근거()["4-3"]) == [
        ("하이브는 음악과 기술을 접목하고 있다.", "조각 10·신규사업전망")
    ]


def test_이_칸에_없는_근거번호의_문장은_표시하지_않는다():
    """다른 칸의 번호가 검증을 지나도 잘못된 항목에 놓지 않는 마지막 안전핀."""
    문장 = [Sentence("다른 칸의 문장이다.", "1-1")]

    assert to_cited_lines(문장, _근거()["4-3"]) == []


