def test_current_constraint_and_separate_response(body, problem, expected):
    _, problems, rejected = split(response(text=body, problem=problem), body=body)
    assert len(problems) == expected
    if expected:
        assert not rejected and problems[0].exact_text == body
    else:
        assert rejected
