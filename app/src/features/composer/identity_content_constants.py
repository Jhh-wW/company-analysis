"""기업 정체성과 핵심 요약에서 행정정보 단독 문장을 구분하는 좁은 문법."""

import re


IDENTITY_ADMINISTRATIVE_ONLY = "identity_administrative_only"
IDENTITY_SECTION_ID = "identity"

# 사업의 관계·활동이 함께 있으면 행정정보와 섞인 문장을 통째로 버리지 않는다.
# '주소' 하나로 물류·주소 검증 서비스가 빠지지 않도록, 아래의 완결 문법과 함께 쓴다.
IDENTITY_BUSINESS_ACTIVITY_RE = re.compile(
    r"(?:제공|판매|제조|개발|운영|중개|연결|공급|배송|운송|유통|생산|연구|진단|치료|"
    r"설계|구축|가공|영위|수출|수입|보관|투자|진출|지원|해결|확장)"
    r"(?:하|한|할|해|했|되|된|될|받|을|를|과|와|\s|·|및)"
    r"|(?:고객|이용자|사용자|가맹점|판매자|구매자)(?:에게|를|을|와|과|의)"
    r"|(?:주요|주력|핵심)\s*(?:사업|제품|서비스)"
    r"|(?:전문|전업)\s*(?:기업|업체|회사|제조사|공급사)"
    r"|(?:기업|회사|업체|제조사|공급사|사업자)인\s"
    r"|(?:매출|수익)\s*(?:구성|비중)"
    r"|(?:매출|수익|영업이익|순이익)(?:액)?(?:은|는|이|가)"
    r"|(?:업체|제조사|공급사|사업자)\s"
)
IDENTITY_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+|[\n;]+")

# 문서별 대표자 표기는 뒤 절에서 직함을 생략해도 사업 설명이 아니다.
# 문서 표지와 짧은 인명 값, 기재 종결형까지 닫힌 문형으로 확인한다.
# '문서' 자체나 임의의 추가 절을 메타정보로 간주하지 않는다.
_DOCUMENT_PERSON_VALUE = r"문서\s+[A-Z0-9]{1,4}(?:에서는|에서|\s*기준)\s+[가-힣]{2,5}"
IDENTITY_DOCUMENT_PERSON_METADATA_RE = re.compile(
    r"(?:감사보고서\s*기준으로\s*)?(?:회사의\s*)?대표이사(?:는|은)\s*"
    r"(?:감사보고서\s*기준으로\s*)?"
    rf"{_DOCUMENT_PERSON_VALUE}(?:\s*,\s*{_DOCUMENT_PERSON_VALUE})+"
    r"(?:으로|로)\s*(?:각각\s*)?(?:기재|명시|표기)"
    r"(?:되어\s*있다|되었다|됐다|되어\s*있어,\s*"
    r"두\s*보고기간\s*사이에\s*대표이사\s*변경이\s*있었음이\s*"
    r"공시\s*자료에서\s*확인된다)[.!]?"
)

# 법적 표제·공시 기수·내부회계 평가를 사업 정체성으로 바꾸지 않는다.
# 같은 문장에 실제 사업 활동이나 실적이 있으면 아래 표지만으로 제외하지 않는다.
IDENTITY_REPORT_METADATA_PATTERNS = tuple(re.compile(pattern) for pattern in (
    r"(?:법적\s*명칭|법인명|상호)(?:은|는|이|가)[^.!?\n]*(?:확인|기재|명시|이다|입니다)",
    r"(?:보고기간\s*종료일|제\s*\d+\s*기(?:말|까지))[^.!?\n]*재무제표[^.!?\n]*(?:공시|작성|제출)",
    r"대표이사[^.!?\n]*재무제표\s*작성\s*책임자\s*표기[^.!?\n]*확인",
))
IDENTITY_INTERNAL_CONTROL_METADATA_RE = re.compile(
    r"내부회계관리제도[^.!?\n]*(?:효과적|효과성|적정)[^.!?\n]*(?:판단|평가|보고|기술)"
)
# 평가 문맥의 이 두 정형 구절만 제거한 뒤 사업활동을 찾는다.
# '설계·운영' 단어를 전역으로 지우면 같은 문장 속 제품 설계·공장 운영까지 잃는다.
IDENTITY_INTERNAL_CONTROL_ACTIVITY_RE = re.compile(
    r"내부회계관리제도\s*설계\s*및\s*운영\s*개념체계"
    r"|(?:효과적으로|적정하게)\s*(?:설계(?:되어|되고|되었고|되었으며)\s*)?"
    r"운영(?:되고|되어|하고)\s*있"
)
# 메타정보를 찾았더라도 모르는 추가 절까지 행정정보로 단정하지 않는다.
# '기술하고 있다'처럼 분리된 보조용언만 예외로 두며, 임의의 명사 문장은 남긴다.
IDENTITY_METADATA_CLAUSE_SPLIT_RE = re.compile(
    r",\s*|(?:이며|이고|되며|으며|하고|하며|지만|있어)\s+"
)
IDENTITY_METADATA_CLAUSE_RE = re.compile(
    r"법적\s*명칭|법인명|상호|대표이사|보고기간\s*종료일"
    r"|제\s*\d+\s*기(?:말|까지)?|재무제표|내부회계관리제도"
)
IDENTITY_METADATA_AUXILIARY_RE = re.compile(r"(?:있다|있습니다|있음)[.!]?")
# 앞 절이 내부회계 평가일 때만 '이에 대한 감사 검토'를 같은 메타 절로 본다.
# 감사인이 제품을 검토하거나 다른 사업 행위를 한 문장은 이 문법에 들지 않는다.
IDENTITY_METADATA_AUDIT_TAIL_RE = re.compile(
    r"(?:외부\s*)?감사인(?:이|은)\s*(?:이에|그에)\s*대한\s*"
    r"검토(?:를)?\s*실시(?:하였다|했습니다|하였습니다|했다)[.!]?"
)

# 한 문장의 주제부만 허용한다. 접속절이 있으면 전체를 행정정보로 단정하지 않는다.
_SUBJECT = r"(?:[^,;.!?\n]{1,80}?(?:은|는|의)\s*)?"
_DATE = r"(?:\d{4}\s*년(?:\s*\d{1,2}\s*월(?:\s*\d{1,2}\s*일)?)?|\d{4}[-./]\d{1,2}[-./]\d{1,2})"
_ENDING = r"(?:이다|입니다|이었다|이었습니다|임)"
_ADDRESS = (
    r"(?=[^.!?;\n]*(?:특별시|광역시|특별자치|[가-힣]{2,}(?:시|군|구|로|길)))"
    r"[가-힣A-Za-z0-9()·,\-\s]+?"
)
IDENTITY_ADMINISTRATIVE_PATTERNS = tuple(re.compile(pattern) for pattern in (
    rf"{_SUBJECT}{_DATE}\s*(?:에\s*)?설립(?:되었다|됐다|되었습니다|되었음|된\s*(?:회사|법인){_ENDING})[.!]?",
    rf"{_SUBJECT}설립(?:일|연도)(?:은|는|이|가)?\s*{_DATE}\s*{_ENDING}[.!]?",
    rf"{_SUBJECT}(?:납입\s*)?자본금(?:은|는|이|가)?\s*(?:약\s*)?\d[\d,.]*\s*(?:천|백만|억|조)?\s*(?:원|달러|USD)\s*{_ENDING}[.!]?",
    rf"{_SUBJECT}(?:본점|본사)(?:\s*(?:소재지|주소))?(?:은|는|이|가)?\s*{_ADDRESS}\s*(?:에\s*)?(?:있다|있습니다|위치한다|위치해\s*있다|소재한다|소재하고\s*있다|{_ENDING})[.!]?",
    rf"{_SUBJECT}{_ADDRESS}\s*에\s*(?:본점|본사)(?:을|를)\s*두고\s*(?:있다|있습니다)[.!]?",
))
IDENTITY_CONNECTED_CLAUSE_RE = re.compile(r"(?:이며|이고|으며|하고|하며|하는|하여|했던|위해|면서|지만)\s")
