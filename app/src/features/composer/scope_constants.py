# ── 현재 관계 단정의 «누구에 대한» 결속 — 주체·대상과 술어를 같은 자리에서 본다 ──
# 연결 어미(-며·-고·-으나·-지만·-는데) 뒤 띄어쓰기는 술어 단위의 경계다. 목적격
