# 지분 보유 단정 — 「<법인>을 100% 지분으로 소유」·「<법인>는 100% 지분으로 소유되고」
# (백분율 먼저), 「<법인>의 지분 100%를 보유」·「<법인> 지분율은 100%이다」(지분 먼저).
