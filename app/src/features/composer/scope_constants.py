# 능동 제외 서술 「(회사는) X를 … 제외하였습니다」의 주어는 제외한 쪽이고, 제외된 법인은
# 목적어다. 수동 「X는 … 제외되었습니다」만 주어가 제외된 법인이다(2026-09-23 B 수정 재검토 R3).
