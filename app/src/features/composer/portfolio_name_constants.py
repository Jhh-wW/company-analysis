"""3장 제품·서비스명 접지 검사의 결정론 상수.

★ 왜 별도 상수 파일인가 — 이 잣대의 소비자는 두 곳이다. 작가 카드를 걸러내는
  ``diagram_check._drop_ungrounded_portfolio_rows``와, 결정적 이름 표를 만드는
  ``portfolio_name_table._verified_names``. 두 곳이 같은 값을 보지 않으면
  「검사는 통과인데 화면에서는 비워지는」 칸이 다시 생긴다. 값을 이 한 파일에
  두면 한쪽만 고쳐지는 표류가 구조적으로 불가능해진다.

★ 회사·업종 분기는 두지 않는다. 아래 두 값은 어느 회사에나 같게 적용된다.
"""

from __future__ import annotations

import re
from typing import Final


#: 이름을 «부분»으로 가르는 글자. 괄호만 가른다.
#:
#: ★ 왜 괄호인가 (2026-09-11 소규모 회사 실측) — 작가는 3장 이름을 자주
#:   ``분류(원문 표현)`` 모양으로 적는다. 실측 보고서의 이름
#:   「제품(전기전자 제품 및 산업용 장비)」은 «제품»과 «전기전자 제품 및
#:   산업용 장비»가 공시 원문에 따로따로 있는데도, 칸 전체를 통짜 부분문자열로
#:   요구하는 옛 잣대에서 접지 실패가 나 2·3장 매출 구성 카드가 전멸했다.
#:   압축된 통짜 이름 「제품전기전자제품및산업용장비」는 그 회사 공시 어디에도
#:   없다 — 범위를 넓히는 것만으로는 살아나지 않는 결함이었다.
#: ★ 쉼표·가운뎃점은 가르지 않는다. 그것까지 가르면 「A, B」가 A와 B가 각각
#:   어딘가에 있기만 하면 통과해 «없는 이름»을 조립할 수 있다.
PORTFOLIO_NAME_PART_SPLIT_RE: Final[re.Pattern[str]] = re.compile(
    r"[()（）\[\]{}]"
)

#: 괄호 «안» 부분 하나를 통째로 잡아내는 자리. 안쪽만 따로 꺼내 쓴다.
#:
#: ★ 왜 «구간»이 필요한가 — 이름의 머리(괄호 밖 본체)를 구하려면 괄호 안을
#:   통째로 지워야 한다. 가르기만 하면 「기타(A/S) 등」이 «기타 / as / 등»
#:   세 토막이 되어, 식별에 쓰이지 않는 꼬리 「등」이 따로 검사를 받는다.
#: ★ NFKC 정규화 뒤에 쓰므로 전각 괄호도 반각으로 들어온다. 그래도 전각을
#:   목록에 남겨 두는 것은 정규화 전 문자열에 실수로 쓰여도 같게 읽히게 하려는
#:   것이다.
PORTFOLIO_NAME_BRACKET_SPAN_RE: Final[re.Pattern[str]] = re.compile(
    r"[(\[{（［｛]([^)\]}）］｝]*)[)\]}）］｝]"
)

#: 괄호 «안» 부분이 이 글자 수보다 짧으면 접지로 인정하지 않는다.
#:
#: ★ 왜 필요한가 — 부분 단위 검사는 잣대를 느슨하게 만든다. 한 글자짜리 조각은
#:   웬만한 문서 어디에나 있어서, 그것만으로 통과시키면 「카카오(T)」처럼 서로
#:   다른 조각의 낱말을 이어 붙인 이름이 통과한다.
#: ★ 머리에는 걸지 않는다 (2026-09-11 재검토) — 「기타(A/S) 등」의 꼬리 「등」을
#:   따로 재면 저장소가 스스로 정당하다고 못 박아 둔 이름이 막힌다
#:   (`product_names/constants.py`의 이름 모양 설명). 머리는 괄호 안을 지운
#:   나머지 «하나»로 보고 인용 조각에서 통째로 확인한다.
PORTFOLIO_NAME_MIN_PART_CHARS: Final[int] = 2

#: 한 글자여도 인정하는 «법인격 표기». 압축된 표면으로 적는다.
#:
#: ★ 왜 예외가 필요한가 (2026-09-11 재검토 실측) — 「(주)수퍼톤」·「수퍼톤(주)」·
#:   「카카오(유)」는 공시 원문에 글자 그대로 있는 정상 이름인데, 괄호 안이 한
#:   글자라 하한에 걸려 통째로 막혔다. 「(주)」는 이름 파서가 회사명을 잡는
#:   표식이기도 해서, 그 표기의 종속회사가 하나만 있어도 대표 이름 표 «전체»가
#:   안 만들어진다.
#: ★ 닫힌 목록이다. 업종·회사로 갈리지 않고, 법인 종류를 나타내는 한 글자만
#:   담는다(주식회사·유한회사·합자회사·재단법인·사단법인).
PORTFOLIO_NAME_ENTITY_MARKERS: Final[frozenset[str]] = frozenset(
    {"주", "유", "사", "재", "합"}
)
