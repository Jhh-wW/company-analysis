"""중복 삭제 «안전 증명»의 표면형·절 경계·어미 변환 — dedupe 도메인 전용 상수.

★ 왜 필요한가 (2026-09-23 총괄 확정 — 독립 반례 대응)
  3그램 겹침은 «비교 후보»를 고르는 데만 쓴다. 실제 삭제는 지울 문장의 주장절이
  소유 문장의 완전 주장절과 «통째로» 대응할 때만 한다. 겹침 60%는 같은 조건·
  관계·사실이 남았다는 증거가 아니다(짧은 조건 절·상대 교체·방향 교환·금액
  재귀속이 모두 높은 겹침으로 지워졌다).

★ 왜 constants.py에 두지 않나 — 큰 공용 상수 파일은 다른 소유 영역이다.
  이 값들은 `dedupe._owner_cover` 증명만 쓰므로 dedupe 도메인에 둔다.

★ 삭제 증명 표면형은 «의미를 보존»한다. 유사도용 정규화(호환 정규화·소문자화·
  기호 제거)를 여기서 쓰지 않는다 — «-100억원»과 «100억원», «AB»와 «Ab»,
  «①»과 «1»은 다른 표면이다. 지우는 것은 아래에 이름을 붙인 좁은 표시뿐이다.
"""

from __future__ import annotations

import re
from typing import Final

#: 여닫이가 구분되는 인용부호·괄호 짝. 안의 글자는 «잠금» — 어미 변환과 절
#: 경계 판정의 대상이 아니다. 부호 자체는 표면형에 그대로 남긴다(인용 여부도
#: 의미다). 괄호는 인용이 아니지만 안의 글자를 변환하지 않는 쪽이 안전하다.
PROOF_QUOTE_PAIRS: Final[dict[str, str]] = {
    "«": "»", "「": "」", "『": "』", "‘": "’", "“": "”", "(": ")", "[": "]",
    "《": "》", "〈": "〉", "（": "）",
}

#: 여닫이가 같은 글자인 인용부호. 여닫이를 번갈아 센다. 삭제 표면은 호환 정규화를
#: 하지 않으므로 전각 따옴표도 따로 둔다.
PROOF_QUOTE_TOGGLES: Final[frozenset[str]] = frozenset({"'", '"', "＇", "＂"})

#: 영문자 사이의 ASCII 작은따옴표는 인용이 아니라 영어 아포스트로피다
#: (「Leader's」). 인용 여닫이로 세면 뒤쪽 실제 인용의 짝이 어긋난다.
PROOF_APOSTROPHE_NEIGHBOR_RE: Final[re.Pattern[str]] = re.compile(r"[A-Za-z]")

#: 문장 «마지막» 어절 끝에서만 지우는 종결 부호 — 문장이 끝났다는 표시다.
PROOF_SENTENCE_TERMINATORS: Final[frozenset[str]] = frozenset({".", "!", "?", "。"})

#: 절 경계 연결어미 «바로 뒤»에서만 지우는 쉼표 — 절이 이어진다는 표시다.
#: 그 밖 자리의 쉼표(「부품을, 공급한다」·「제시하되,」)는 표면에 남는다.
PROOF_CLAUSE_COMMA: Final[str] = ","

#: 절 경계로 인정하는 나열 연결어미의 끝 글자 — 「…이며/…하며」만.
#: 조건·양보·이유 연결(「…하면」·「…하되」·「…해서」)은 절 경계가 아니다 —
#: 조건이 걸린 절을 잘라 내고 삭제 증거로 쓰지 않기 위해서다.
PROOF_CLAUSE_LINK_SUFFIX: Final[str] = "며"

#: 여러 소유 문장 합집합에서 «명시 주체»로 인정하는 주제 조사.
#: ★ 합집합은 후보의 모든 절이 «같은 주제어 어절»(예: 「가나다전자는」)로 시작할
#:   때만 허용한다. 뒤 절의 주어가 생략되면(「…이며 행동 원칙으로 …」) 그 절의
#:   주체가 앞 절 주제·소유격·인용 속 이름 중 무엇인지 표면으로 증명할 수 없다
#:   (「X의 파트너는 Y이며 …」 반례). 주어를 추측·상속하지 않고 보존한다.
PROOF_TOPIC_PARTICLES: Final[tuple[str, ...]] = ("은", "는")

#: 숫자 천 단위 쉼표 — 값이 같은 표기 차이다(「1,200」=「1200」). 부호·소수점은
#: 그대로 둔다. ASCII 숫자 세 자리 묶음 바로 앞의 쉼표만, 그리고 인용부호·괄호
#: «밖»에서만 지운다 — 인용된 이름(「'Model 1,000'」)은 원문 표기 그대로다.
PROOF_THOUSANDS_COMMA_RE: Final[re.Pattern[str]] = re.compile(
    r"(?<=[0-9]),(?=[0-9]{3}(?![0-9]))"
)

#: 절 «끝» 어절에서만 허용하는 종결형↔연결형 변환의 닫힌 묶음.
#: ★ 같은 묶음 안의 어미를 벗긴 «본체»가 완전히 같아야 한다.
#: ★ 묶음1 — 서술격 조사 「이다」와 그 연결형 「이며」, 모음 뒤 축약형 「다/며」
#:   (「표어는 'X'다」↔「표어는 'X'이며」).
#: ★ 묶음2 — 「하다」 계열 현재 서술 「한다」와 그 연결형 「하며」
#:   (「제시한다」↔「제시하며」).
#: ★ 임의 공통 접두(어간 추정)는 쓰지 않는다 — 「공급하고」↔「공급받고」(방향),
#:   「승인한다」↔「승인하지 않는다」(부정), 「정규직에만」↔「정규직에게도」(조건)를
#:   문법 변형과 구별할 수 없다. 태·시제·조건·방향·부정은 이 묶음에 없다.
PROOF_ENDING_CLASSES: Final[tuple[frozenset[str], ...]] = (
    frozenset({"다", "며", "이다", "이며"}),
    frozenset({"한다", "하며"}),
)

#: 어미를 벗긴 본체의 최소 길이 — 1자 본체는 다른 낱말과 구별할 수 없다.
PROOF_MIN_STEM_CHARS: Final[int] = 2
