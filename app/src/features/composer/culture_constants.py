# ② «누가 맡는지»를 말한 절인가 — 조직 주체와 함께 요구하는 «조직 행위» 표지.
#
# ★ 왜 재무위험 «규정» 블록의 동사 목록을 그대로 쓰지 않나 (실측) — 그 목록은
#   활용형(하다/한다/받다 등)만 인정한다. 그래서 실제 공시 원문의 정당한
#   «누가» 절이 조사 하나 때문에 줄줄이 빠졌다:
#     · 「…위험관리 전담부서인 리스크총괄부의 «검토를» 거쳐…」        → 안 걸림
#     · 「리스크관리위원회는 … 위험 전략에 대한 «의사결정을» 하고 있다」 → 안 걸림
#     · 「이사회를 중심으로 위험관리 체계를 «구축하고» 감독 «책임을» 둔다」 → 안 걸림
#   세 절 다 조직 주체를 분명히 말하고 있어 8장 안내문의 예외(「재무 위험을
#   누가 맡는지 조직으로 설명한 문장」)에 해당한다.
# ★ 그래서 이 블록은 어간을 넓게 담되, «서술어로 쓰였을 때»만 인정한다.
#   어간만 보면 다른 낱말 «안»에 묻힌 글자가 면제를 만든다 — 실측으로 확인한
#   자리: 「스마트교육사업부」의 «교육»이 부서 이름과 함께 걸려, 사람·조직
#   소재가 하나도 없는 절에 면제가 붙었다. 이 구멍이 있으면 조직 이름 하나와
#   그런 명사 하나만 있으면 계약을 우회할 수 있다.
# ★ 그래서 어간 뒤에 «활용 어미 또는 조사»가 붙었는지까지 본다. 조사를 넓게
#   허용하는 이유는 실제 공시 문장이 「검토를 거쳐」·「의사결정을 하고」처럼
#   명사+조사 꼴을 흔히 쓰기 때문이다. 판정의 무게는 여전히 «조직 주체»가
#   진다 — 주체가 없으면 이 목록이 걸려도 면제가 만들어지지 않는다.
#   실측 반례(자본관리·유동성·이자율위험 목표 문장)는 전부 주체가 없어 그대로
#   제외된다. 명사 안에 숨은 두 낱말(「감독당국」·「사업보고서」)은 기존
#   블록과 같은 방식으로 좁혀 제외한다.
# ★ 재무위험 규정 블록의 목록은 «건드리지 않는다» — 그 블록은 이 목록보다
#   좁아야 하고, 둘의 판정 재료가 다르다(후보 표현 vs 인용 원문).
