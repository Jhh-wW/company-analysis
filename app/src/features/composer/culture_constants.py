# ── 8장(인재상·조직문화·일하는 방식) «원문 절» 긍정 계약 ──────────────────
#
# ★ 왜 어휘를 더 넣는 방향이 아닌가 (실측) — 앞의 «범주 + 관리규정» 블록은
#   후보 «표현»을 본다. 그래서 같은 내용을 다른 꼬리로 적으면 그대로 빠져나갔다:
