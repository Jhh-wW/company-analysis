# ── 후보가 «기댄 절»을 고르는 재료 (지지 절 결속) ──────────────────────────
#
# ★ 왜 필요한가 (4차 유료 실행 실측) — 위 계약은 인용 원문을 절로 쪼갠 뒤
#   «어느 한 절에라도» 조직 주체 절이 있으면 후보를 통과시켰다. 그래서 DART
#   서식이 위험관리 절에 거의 언제나 담는 「○○팀의 승인·관리·감독 하에」
#   문장 하나가 그 원문 전체를 8장에 열어 줬다:
#     · 「신용여신은 신용정책 상의 평가기준에 의거하여…」        → 통과
#     · 「당기 중 신용한도를 초과한 거래처는 없었으며…」          → 통과
#     · 「매출채권에 기대신용손실 간편법을…」(무관한 회계 문장)   → 통과
#   그 한 문장만 지운 대조군에서는 셋 다 offcontract로 뒤집혔다. 회사·업종을
#   가리지 않는 범용 결함이다.
#
# ★ 그래서 판정 재료를 «후보가 기댄 절»로 좁힌다. 후보와 내용어(명사·숫자)가
#   가장 많이 겹치는 절만 지지 절로 보고, 그 절이 이 장의 소재를 담고 있을
#   때만 보존한다. 형태소 분석기를 쓰지 않으므로 겹침은 단순 토큰 집합
#   교집합으로 센다 — 조사만 떼고 비교한다.
#
# 지지 절은 겹침이 큰 순서로 최대 CULTURE_SUPPORT_CLAUSE_LIMIT개를 본다.
# 하나만 보지 않는 이유도 실측이다 — 한 문장이 절 경계에서 잘리면 소재 어휘와
# 내용이 서로 다른 조각으로 갈린다. 실측 자리: 「공식 표어는 'Think Brilliant,
# Act Efficient!'이며 Leader's Code로 진실·성실·겸손·사랑을 제시한다」는
# 따옴표 «안»의 느낌표에서 잘려, 소재 낱말(표어)은 앞 조각에 남고 후보가 기댄
# 내용은 뒤 조각에 남는다. 둘째 자리가 그 앞 조각을 되찾아 준다.
# 통과는 지지 절 중 «이 장의 소재»를 담은 절이 하나라도 있을 때만 — 기댈 절을
# 못 찾으면 공개하지 않는다(fail-closed).
CULTURE_SUPPORT_CLAUSE_LIMIT: Final[int] = 2
#: 지지 절로 인정하는 최소 내용어 겹침 수. 0이면 «기댄 절이 없다»는 뜻이다.
CULTURE_SUPPORT_MIN_OVERLAP: Final[int] = 1
#: 내용어로 세는 최소 글자 수. 한 글자 조각(것·수·및)은 어느 절에나 있어
#: 겹침 수를 흔들기만 한다.
CULTURE_SUPPORT_MIN_TOKEN_LENGTH: Final[int] = 2
#: 한글·숫자·영문 이외의 글자에서 낱말을 끊는다 (NFKC·casefold 이후 적용).
CULTURE_SUPPORT_TOKEN_SPLIT_RE: Final[re.Pattern[str]] = re.compile(
    r"[^0-9a-z가-힣]+"
)
#: 낱말 끝에서 떼는 조사. 형태소 분석기가 없으므로 «가장 긴 것 하나»만 뗀다.
#: 어미(–다·–하고)는 넣지 않는다 — 동사를 잘라 서로 다른 낱말을 붙여 놓는다.
#: 길이 내림차순은 코드가 아니라 여기서 보장한다(정렬해 둔다).
