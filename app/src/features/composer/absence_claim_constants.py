"""공식 자료에 «없다»고 단언하는 문장을 가르는 표지 — 장과 무관한 범용 규칙."""

from typing import Final
import re


# ★ review_diagnostic_constants.REVIEW_SCOPE_ITEMS와 반드시 같은 값이어야
#   진단이 UI 표에서 새지 않는다.
ABSENCE_CLAIM_UNSUPPORTED: Final[str] = "absence_claim_unsupported"

# 절을 나누는 경계는 다른 가드와 같은 «문장» 경계를 쓴다. 글자수 상한 같은
# 거리 제한은 쓰지 않는다 — 근거 없는 매직 넘버이기 때문이다.
ABSENCE_CLAUSE_SPLIT_RE: Final[re.Pattern[str]] = re.compile(r"[.!?。\n]+")

# ── ① «무엇에» 없다고 말하는가 — 자료·공시 쪽을 가리키는 지시어 ──────────
#
# ★ 여기를 좁게 잡는 것이 이 가드의 핵심이다 (실측 근거) — 회사가 스스로
#   「당사 해당사항 없습니다」라고 «밝힌» 공시 문장은 정상 인용이고 막으면
#   안 된다. 그래서 주어가 회사인 진술과 «자료를 가리키는» 진술을 가른다.
#   「당사」·「회사」 같은 말은 지시어로 세지 않는다.
# ★ 작성부는 «공식 자료 전체»를 본 적이 없다 — 수집된 조각만 본다. 그래서
#   자료 쪽을 주어로 삼은 부재 단언은 «작성부가 알 수 없는 사실»이다.
#   부재는 확인 범위 안내문(guidance_lines)이 말하고 문장은 말하지 않는다.
# ⚠️ «자료» 뒤에는 반드시 조사가 와야 한다. 조사 없이 인정하면 확인 범위
#   안내문의 「자료가 없다는 뜻은 아닙니다」가 지시어로 잡혀, 정직하게 범위를
#   밝히는 유일한 통로가 막힌다(음성 대조 시험이 이 자리를 못 박는다).
SOURCE_REFERENT_RE: Final[re.Pattern[str]] = re.compile(
    r"공식자료|공개자료|공시자료|참고자료|수집자료|제공된자료|"
    r"공시(?:서류|정보|내용)?(?:에|에서|상|를|을|한)|"
    r"사업보고서|감사보고서|분기보고서|반기보고서|정기보고서|"
    r"보도자료|홈페이지|공식채널|"
    r"원문|원자료|근거자료|"
    # 이 제품에서 「조각」은 수집 근거의 이름이다 — 작성부가 실제로 보는 것이
    # 조각뿐이라, 조각을 주어로 삼은 부재 단언도 같은 거짓말이다.
    r"(?:근거|수집(?:된)?|인용(?:된)?)조각|조각(?:에서|에는|에|상)|"
    r"자료(?:에서|에는|에|상)"
)

# ── ② «없다»고 말하는 술어 ────────────────────────────────────────────────
#
# 「확인되지 않는다」·「기재되어 있지 않다」처럼 자료 쪽을 주어로 세운 부재
# 술어만 모은다. 「어렵다」·「제한적이다」 같은 정도 표현은 부재 단언이
# 아니므로 넣지 않는다 — 그런 문장은 기존 의미 검수가 판정한다.
#
# ★ 조사 하나에 기대지 않는다 (실측) — 「기재가 되어 있지 않다」는 「기재되어
#   있지 않다」와 같은 말인데, 조사 「가」 하나 때문에 앞의 모양만 적으면
#   빠져나간다. 그래서 명사+되다 갈래는 조사를 선택 항목으로 둔다.
#
# ★ 어휘 목록의 한계를 여기 적어 둔다 (독립 검토 실측) — 같은 커밋이 8장
#   쪽에서는 「어휘를 늘리는 방향은 이미 실패가 실측됐다」고 진단했는데 이
#   가드는 정확히 그 방향이다. 표현을 바꾸면 뚫린다:
#   「담겨 있지 않다」·「나오지 않는다」·「부재하다」·「등장하지 않는다」가
#   실제로 통과했다. 아래는 그 네 갈래를 «어간 기준»으로 담은 것이며,
#   목록에 없는 새 표현은 여전히 통과한다.
# ★ 그래서 이 가드는 «유일한» 방어가 아니다. 8장 지침의 「없다고 적지도
#   않는다」가 발생 자체를 줄이고, 부재는 확인 범위 안내문이 말한다.
#   근본 해법(자료 쪽 주어 + 부정 극성을 문법으로 판정)은 이 커밋 범위 밖이다.
ABSENCE_PREDICATE_RE: Final[re.Pattern[str]] = re.compile(
    # ① «찾/확인할 수 없다» 갈래
    r"(?:찾을|찾아볼|확인할|파악할|발견할|검색할|알)수(?:는)?없|"
    # ② «~되지/~지 않는다» 갈래 — 어간 + (되지|하지|지) + 않/못
    r"(?:확인|파악|검색|발견|기재|기술|서술|명시|언급|수록|포함|공시|공개|"
    r"제시|제공|존재)(?:되|하)?지(?:는)?(?:않|못)|"
    r"(?:드러나|나타나|나오|등장하|밝히|밝혀지|보이)지(?:는)?않|"
    # ③ «~(가) 되어/담겨 있지 않다» 갈래 — 조사가 끼어들 수 있다
    r"(?:기재|언급|명시|포함|서술|기술|수록|반영)(?:가|이|은|는|를)?"
    r"(?:되어|돼)?있지않|"
    r"(?:담겨|담고|나와|들어)있지않|담기지않|"
    # ④ «부재하다» 갈래
    r"부재(?:하|다|이다|한|였)|"
    # ⑤ «~(이) 없다» 갈래 — 자료 지시어가 같은 절에 있을 때만 뜻이 선다.
    #    지시어 요구는 호출부(absence_claim_problem)가 이미 하고 있다.
    r"없(?:다|었|습니다|으며|고|는)"
)
