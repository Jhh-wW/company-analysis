"""공식 자료에 «없다»고 단언하는 문장을 가르는 표지 — 장과 무관한 범용 규칙."""

from typing import Final
import re


# ★ review_diagnostic_constants.REVIEW_SCOPE_ITEMS와 반드시 같은 값이어야
#   진단이 UI 표에서 새지 않는다.
ABSENCE_CLAIM_UNSUPPORTED: Final[str] = "absence_claim_unsupported"

# ★ 2026-09-16 사용자 결정 — 문장을 뺀 자리에 「확인 범위: …」 안내문을 남기지 않는다.
#   자료가 적으면 독자는 못 찾았다고 알아서 읽는다. 뺀 사실은 진단(ABSENCE_CLAIM_UNSUPPORTED)에만 남긴다.

# 절을 나누는 경계는 다른 가드와 같은 «문장» 경계를 쓴다. 글자수 상한 같은
# 거리 제한은 쓰지 않는다 — 근거 없는 매직 넘버이기 때문이다.
ABSENCE_CLAUSE_SPLIT_RE: Final[re.Pattern[str]] = re.compile(r"[.!?。\n]+")

# ── ① «무엇에» 없다고 말하는가 — 자료·공시 쪽을 가리키는 지시어 ──────────
#
# ★ 여기를 좁게 잡는 것이 이 가드의 핵심이다 (실측 근거) — 회사가 스스로
#   「당사 해당사항 없습니다」라고 «밝힌» 공시 문장은 정상 인용이고 막으면
#   안 된다. 그래서 주어가 회사인 진술과 «자료를 가리키는» 진술을 가른다.
#   「당사」·「회사」 같은 말은 지시어로 세지 않는다.
# ★ 작성부는 «공식 자료 전체»를 본 적이 없다 — 수집된 조각만 본다. 그래서
#   자료 쪽을 주어로 삼은 부재 단언은 «작성부가 알 수 없는 사실»이다.
#   부재는 문장으로 말하지 않는다(안내문도 2026-09-16부터 싣지 않는다).
# ⚠️ «자료» 뒤에는 반드시 조사가 와야 한다. 조사 없이 인정하면 「자료가 없다는
#   뜻은 아닙니다」 같은 정상 문장이 지시어로 잡힌다(음성 대조 시험이 이 자리를 못 박는다).
# ★ 「공시가·공시는」 주격 갈래 (2026-09-23 운영 PDF 27e9f03 실측) — 8장에
#   「노사 관계 … 공식 선언이나 정책 공시가 확인되지 않는다」가 «해석» 등급으로
#   인쇄됐다. 술어(확인되지 않는다)는 이미 목록에 있었는데 지시어가 조사
#   「에/에서/상/를/을/한」만 받아 주격 「공시가」를 지시어로 세지 않았다.
#   「공시가격」(공시된 가격)은 자료 지시어가 아니므로 뒤에 「격」이 오면 뺀다.
SOURCE_REFERENT_RE: Final[re.Pattern[str]] = re.compile(
    r"공식자료|공개자료|공시자료|참고자료|수집자료|제공된자료|"
    r"공시(?:서류|정보|내용)?(?:에|에서|상|를|을|한)|"
    r"공시(?:가(?!격)|는)|"
    r"사업보고서|감사보고서|분기보고서|반기보고서|정기보고서|"
    r"보도자료|홈페이지|공식채널|"
    r"원문|원자료|근거자료|"
    # 이 제품에서 「조각」은 수집 근거의 이름이다 — 작성부가 실제로 보는 것이
    # 조각뿐이라, 조각을 주어로 삼은 부재 단언도 같은 거짓말이다.
    r"(?:근거|수집(?:된)?|인용(?:된)?)조각|조각(?:에서|에는|에|상)|"
    r"자료(?:에서|에는|에|상)"
)

# ── ② «없다»고 말하는 술어 ────────────────────────────────────────────────
#
# 「확인되지 않는다」·「기재되어 있지 않다」처럼 자료 쪽을 주어로 세운 부재
# 술어만 모은다. 「어렵다」·「제한적이다」 같은 정도 표현은 부재 단언이
# 아니므로 넣지 않는다 — 그런 문장은 기존 의미 검수가 판정한다.
#
# ★ 조사 하나에 기대지 않는다 (실측) — 「기재가 되어 있지 않다」는 「기재되어
#   있지 않다」와 같은 말인데, 조사 「가」 하나 때문에 앞의 모양만 적으면
#   빠져나간다. 그래서 명사+되다 갈래는 조사를 선택 항목으로 둔다.
#
# ★ 어휘 목록의 한계를 여기 적어 둔다 (독립 검토 실측) — 같은 커밋이 8장
#   쪽에서는 「어휘를 늘리는 방향은 이미 실패가 실측됐다」고 진단했는데 이
#   가드는 정확히 그 방향이다. 표현을 바꾸면 뚫린다:
#   「담겨 있지 않다」·「나오지 않는다」·「부재하다」·「등장하지 않는다」가
#   실제로 통과했다. 아래는 그 네 갈래를 «어간 기준»으로 담은 것이며,
#   목록에 없는 새 표현은 여전히 통과한다.
# ★ 그래서 이 가드는 «유일한» 방어가 아니다. 8장 지침의 「없다고 적지도
#   않는다」가 발생 자체를 줄인다.
#   근본 해법(자료 쪽 주어 + 부정 극성을 문법으로 판정)은 이 커밋 범위 밖이다.
# ★ 「선언」·「자료」 갈래 (2026-09-23 운영 PDF 27e9f03 실측) — 아래 세 문장이
#   이 목록을 그대로 지나 표지 04·8장·9장에 인쇄됐다. 셋 다 지시어는 잡혔고
#   술어만 목록 밖이었다:
#     · 9장 「감사보고서와 공시 자료에는 … 특허 보유 … 공식 «선언이 없다»」(인용 3개·확인 등급)
#     · 표지 04·9장 「회사는 공식 자료에서 자신의 차별점을 명시적으로 «선언하지 않았다»」
#     · 8장 「조직개편 … 승인 절차에 관한 공식 공시 «자료가 없다»」
#   9장 문장은 같은 감사보고서 주석 7에 산업재산권 잔액이 있어 독자에게 사실
#   오류로 읽힐 수 있다. 잔액이 곧 특허 보유는 아니므로 «확인된 모순»으로
#   단정하지 않고, 작성부가 알 수 없는 «문서 전체 부재 단언»으로 다뤄 뺀다.
#   「자료」를 ⑤에 넣으면 안내문 변형 「공식 자료가 없다는 뜻은 아닙니다」가
#   걸리므로, «부재 자체를 부정하는 절»은 ABSENCE_NEGATED_RE로 먼저 뺀다.
ABSENCE_PREDICATE_RE: Final[re.Pattern[str]] = re.compile(
    # ① «찾/확인할 수 없다» 갈래
    r"(?:찾을|찾아볼|확인할|파악할|발견할|검색할|알)수(?:는)?없|"
    # ② «~되지/~지 않는다» 갈래 — 어간 + (되지|하지|지) + 않/못
    r"(?:확인|파악|검색|발견|기재|기술|서술|명시|언급|수록|포함|공시|공개|"
    r"제시|제공|존재|선언)(?:되|하)?지(?:는)?(?:않|못)|"
    r"(?:드러나|나타나|나오|등장하|밝히|밝혀지|보이)지(?:는)?않|"
    # ③ «~(가) 되어/담겨 있지 않다» 갈래 — 조사가 끼어들 수 있다
    r"(?:기재|언급|명시|포함|서술|기술|수록|반영)(?:가|이|은|는|를)?"
    r"(?:되어|돼)?있지않|"
    r"(?:담겨|담고|나와|들어)있지않|담기지않|"
    # ④ «부재하다» 갈래
    r"부재(?:하|다|이다|한|였)|"
    # ⑤ «~(이) 없다» 갈래 — «무엇이» 없는지에 결속한다. 지시어만 보고 「없다」를
    #    통째로 인정하면 「사업보고서에 따르면 당사는 노동조합이 없다」처럼
    #    회사가 밝힌 사실을 자료를 근거로 전달하는 정상 문장까지 막힌다
    #    (실측: 그 넓힘 한 줄로 정상 문장 10건 중 9건이 제외로 뒤집혔다).
    #    앞의 ②③④가 표현 바꾸기 네 갈래를 이미 다 잡으므로 여기를 넓힐 이유도 없다.
    #    ★ 「선언」·「자료」는 2026-09-23 실측으로 «부재의 대상» 자리에 실제로
    #      쓰인 낱말이라 더한다. 「없이」(「자료 없이」)는 부재 단언이 아니라
    #      수단 서술이므로 뺀다.
    r"(?:기재|언급|명시|서술|기술|수록|반영|내용|정보|설명|선언|자료)"
    r"(?:가|이|은|는|도)?없(?!이)"
)

# ── ③ 판정 «전에» 절에서 지우는 두 구절 — 부재가 아닌 것을 부재로 읽지 않기 위해 ──
#
# 둘 다 절을 통째로 면제하지 않고 «그 구절만» 지운 뒤 나머지를 판정한다.
# 절 전체를 건너뛰면 「자료가 없다는 뜻은 아니지만 공시에는 관련 선언이 없다」
# 처럼 같은 절의 진짜 부재 단언까지 면제된다(총괄 검토 지적, 회귀 시험 있음).
#
# ③-a «부재 자체를 부정하는» 구절 — 「(공식 자료가) 없다는 뜻은 아닙니다/아니지만」.
#   ⑤에 「자료」를 넣은 뒤로는 이 안내문 변형이 지시어(공식 자료)와 술어(자료가
#   없)를 함께 갖게 되므로, 부정된 부재의 주어(앞 8글자까지)와 함께 지운다.
#   「아닙니다」는 받침이 합쳐져 «아닙»으로 시작하고, 「아니지만/아니고/아니며」는
#   이어지는 절을 살려야 하므로 연결어미까지만 지운다.
ABSENCE_NEGATED_RE: Final[re.Pattern[str]] = re.compile(
    r"[가-힣]{0,8}없다는(?:뜻|의미|말|것)(?:은|이|도)?"
    r"(?:아니(?:지만|고|며|다|라)?|아닙니다)"
)
# ③-b «출처가 그렇게 밝혔다»는 보고 구절 — 「…선언하지 않았다고 밝혔다」·
#   「…없다고 적혀 있다」. 회사가 «밝힌» 부정은 회사 행동의 사실이지 작성부의
#   문서 전체 부재 단언이 아니다(총괄 검토: 「회사는 공시에서 중간배당을 선언하지
#   않았다고 밝혔다」). 부정 어미와 보고 동사를 함께 지워 ②·⑤ 술어가 남지
#   않게 한다. 보고 동사 목록은 닫힌 것이라 「…없다고 판단된다」류는 지우지 않는다.
ABSENCE_REPORTED_RE: Final[re.Pattern[str]] = re.compile(
    r"(?:않|없|못)(?:았|었|는|음)?다고"
    r"(?:밝혔|밝히|밝힌|공시했|공시하|공시한|설명했|설명하|설명한|"
    r"적혀|적었|적은|기재했|기재돼|기재된|명시했|명시돼|명시된|"
    r"말했|전했|보고했|답했)"
)
