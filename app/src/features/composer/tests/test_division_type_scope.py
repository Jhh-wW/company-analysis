def test_scope_consumer_rejects_subtype_but_keeps_generic_division():
    source = {"own": "주식회사 가온에 대한 미수금에는 분할 관련 미정산 자산 금액이 포함되어 있다."}
    assert scope_problem("인적분할로 분리된 주식회사 가온과 미수금이 남아 있다.", source) == SCOPE_CONDITION_UNBOUND
    assert division_type_scope_problem("분할로 분리된 주식회사 가온과 미수금이 남아 있다.", source) == ""
