def _도식_판정(cells, 원문):
    """실제 운영 진입점(check_diagrams)으로 행 하나를 판정한다."""

    import json as _json

    from src.features.composer.diagram_check import check_diagrams
    from src.features.composer.port import (
        CollectedFragment, ComposedReport, ComposedSection, FlowRow,
    )

    행 = FlowRow(cells=tuple(cells), citations=("8",))
    보고서 = ComposedReport(
        sections=(ComposedSection("culture", (), flow_rows=(행,)),)
    )
    조각 = (CollectedFragment(fragment_id="8", kind="공시", text=원문),)

    def ask(_prompt: str) -> str:
        return _json.dumps(
            {"판정": [{"번호": 1, "결과": "참"}]}, ensure_ascii=False
        )

    검증됨, 사유들 = check_diagrams(보고서, 조각, ask)
    문화장 = next(s for s in 검증됨.sections if s.section_id == "culture")
    return 문화장.flow_rows, 사유들


