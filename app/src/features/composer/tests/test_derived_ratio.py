def _값이_많은_조각(개수: int) -> tuple[CollectedFragment, ...]:
    """「합 계」 줄 `개수`개가 든 조각. 앵커 1개면 조합은 개수-1이다.

    ★ 총액 줄로 만드는 이유 — 분모가 총액 줄이어야 짝이 생긴다. 상한만 보려는
      시험이므로 그 조건을 충족시킨 뒤에 «개수»만 흔든다.
    """

    줄 = "\n".join(
        f"합 계\n {(index + 1) * 1_000_000:,}" for index in range(개수)
    )
    머리 = "(단위: 원)\n 갑부문 명세\n"
    return (
        CollectedFragment(fragment_id="45", kind="재무", text=머리 + 줄),
    )


