# -*- coding: utf-8 -*-
"""검증이 «무엇을 얼마나 지웠는지» 반드시 남기게 못 박는다.

★ 왜 이 파일이 생겼나 (실측)
  ─────────────────────────────────────────────────────────
  현대카드 보고서의 「해석」 비율이 40%였다(기준 보고서는 12~18%).
  본문도 45문장 → 25문장으로 줄었다.

  ★ 그런데 서버 로그로는 원인을 «찾을 수 없었다.**
    - 강등 경로가 4갈래인데 로그는 «한 갈래»만 셌다
      → 로그만 보면 「강등 1건」이라 원인이 아닌 것처럼 보인다
    - 의미 검수의 «성공 경로»는 단 한 줄도 안 남겼다
      (실패했을 때만 경고 — 이번엔 성공했으므로 완전 침묵)
    - 수치 안전 삭제(가장 큰 삭제)는 보고서 «안»에만 적히고 로그엔 0건

  결국 dedupe 로그를 역산하고 결과 HTML 을 파싱해서야 원인을 찾았다.
  **추측 대신 «새는 곳부터 재는 것»이 근본 해결이다** (27장 결함 D).

★ 이 시험이 지키는 것
  숫자를 맞추는 시험이 아니다. 「지웠으면 그 사실이 «반드시» 로그에 남는가」를 본다.
"""

from __future__ import annotations

import logging

from src.features.composer import pipeline as composer_pipeline
from src.features.composer import verify as composer_verify


def _소스(모듈) -> str:
    import inspect

    return inspect.getsource(모듈)


# ══════════════════════════════════════════════════════════
# ① 강등 4갈래를 «전부» 세는가
# ══════════════════════════════════════════════════════════


def test_인용없는_확인의_해석강등도_센다() -> None:
    """★ 이 강등은 «세지 않고» 있었다 — 로그만 보면 원인이 아닌 것처럼 보인다.

    문장 «수»가 안 줄어드는 강등이라 기존 카운터로는 잡히지 않는다.
    """
    소스 = _소스(composer_verify)

    assert "강등_라벨정합" in 소스, (
        "★ 인용 없는 「확인」의 해석 강등을 세지 않으면 해석 비율의 출처를 못 찾는다"
    )
    assert "인용없는 확인→해석 강등 %d" in 소스, "로그 문구에도 나와야 한다"


def test_의미검수_성공경로도_남긴다() -> None:
    """★ 실패했을 때만 경고가 있었다 — 성공하면 «완전 침묵»이었다.

    이번 실측에서 의미 검수는 «정상 응답»을 받았다. 그런데 그 안에서 몇 개가
    참/거짓/애매로 갈렸는지 알 방법이 없어 해석 40%의 출처를 놓쳤다.
    """
    소스 = _소스(composer_verify)

    assert "의미 검수 판정(문장 %d)" in 소스, "★ 성공 경로가 침묵하면 원인을 못 찾는다"
    for 판정 in ("참 %d", "거짓→재작성 %d", "거짓→제거 %d", "애매→해석강등 %d"):
        assert 판정 in 소스, f"판정 «{판정}»이 로그에 없다"


# ══════════════════════════════════════════════════════════
# ② 가장 큰 삭제가 서버 로그에 남는가
# ══════════════════════════════════════════════════════════


def test_수치안전_삭제가_서버로그에_남는다() -> None:
    """★ 이 단계가 «가장 많이» 지우는데 서버 로그엔 흔적이 0이었다.

    실측(현대카드): 최소 16문장이 여기서 사라졌다. 그 사실은 보고서 «안»에만
    적혀 있어서, 운영자가 로그만 보면 「검증은 3문장만 뺐다」로 잘못 읽는다.
    """
    소스 = _소스(composer_pipeline)

    assert "수치 안전 제외" in 소스, (
        "★ 가장 큰 삭제가 로그에 안 남으면 다음 사람도 원인을 못 찾는다"
    )
    assert "removed_section_counts" in 소스


# ══════════════════════════════════════════════════════════
# ③ 로그가 비밀을 흘리지 않는가  ← 안전선
# ══════════════════════════════════════════════════════════


def test_검증_로그에_문장_본문을_넣지_않는다() -> None:
    """★ 개수와 사유만 남긴다. 문장 본문이 로그로 새면 회사 원문이 유출된다.

    이 저장소 규칙: 「로그에 회사 원문·비밀 링크·개인정보를 넣지 마라.
    개수·사유 코드만 남긴다.」
    """
    소스 = _소스(composer_verify)

    # 새로 넣은 로그 문장들이 «문장 객체»를 직접 찍지 않는지 본다.
    금지패턴 = (
        "sentence.text",
        "item.sentence.text",
        ".text,",
    )
    로그줄 = [
        줄 for 줄 in 소스.splitlines()
        if "logger." in 줄 or ("의미 검수 판정" in 줄) or ("코드 검증 처분" in 줄)
    ]
    본문 = "\n".join(로그줄)
    새어나온것 = [패턴 for 패턴 in 금지패턴 if 패턴 in 본문]

    assert not 새어나온것, f"★ 로그에 문장 본문이 섞였다: {새어나온것}"
