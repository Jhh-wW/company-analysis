"""명시 행위자 앞에 붙는 짧은 사업 범위구의 주어 검사 경계."""

import re

# 범위의 사실성은 사업 범위 검사에 남긴다. 술어·인용·조건을 주어 앞
# 장식으로 지워 다른 회사의 행위를 직접 행위로 만들지 않는다.
BUSINESS_PREFIX_MAX_CHARS = 80
BUSINESS_PREFIX_RE = re.compile(
    r"[가-힣A-Za-z0-9·& /-]+(?:부문|사업|분야)에서\s+"
)
BUSINESS_PREFIX_UNBOUND_RE = re.compile(
    r"주식회사|㈜|회사|기업|업체|타사|타인|경쟁사|업계|산업전반|"
    r"종속|자회사|계열사|그룹|인용|설명|주장|언급|따르면|의하면|"
    r"경우|조건|가정|아니|아닌|않|못|제외|대신|향후|과거|예정|계획|"
    r"했다고|한다는|하는|했던|있다|없다"
)
