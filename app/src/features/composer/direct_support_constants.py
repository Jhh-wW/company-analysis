# ② 인과 단언의 «관계 근거» — 파서와 프롬프트가 함께 요구한다
# ══════════════════════════════════════════════════════════
#
# ★ 실제 사례: 원문은 「신용비용 부담**에도 불구하고** 순영업수익의 안정적인
#   창출을 통해 … 당기순이익을 시현」인데, 후보는 「신용비용 부담 증가가
#   이익 감소의 **주요 배경이었다**」로 적었다. 같은 대상을 두고 원문은
#   「그럼에도」라고 하고 후보는 「그래서」라고 한 것이다.
# ★ 문법 표면만으로 이 뒤집기를 잡으려던 시도는 실패했다 — 후보가 원인으로 지목한
#   구를 원문에서 그대로 찾을 수 없어(요약·재서술) 대조 자체가 성립하지 않았다.
#   실패 기록은 .local-artifacts/resume-20260909-semantic-direct-support-fix 에 남겼다.
#   그래서 «어느 구절이 그 관계를 뒷받침하는가»를 검수 응답이 직접 대게 한다.
#: 후보가 인과를 «단언»할 때만 쓰는 표지. 「배경」처럼 홀로 쓰이는 낱말이 아니라
#: 「주요/주된 + 원인/배경/요인」의 결합만 본다 — 서술적 배경 설명을 막지 않는다.
CLAIM_CAUSE_RE: Final[re.Pattern[str]] = re.compile(
    r"(주요|주된|핵심|가장\s*큰)\s*(원인|배경|요인)"
)
#: 그 표지 «바로 뒤»가 단언을 도로 물리면 이 검사는 아무 판정도 하지 않는다.
#:
#: ★ 「환율 변동은 주요 원인이 «아니다»」는 정상적인 부정 진술이지 인과 단언이
#:   아니다. 표지만 세면 이런 문장이 관계 근거를 대지 못해 통째로 삭제된다.
#:   보조 가드는 «긍정으로 명시한 주요 원인»만 보고, 문장 전체의 옳고 그름은
#:   기존 의미 검수(LLM)가 계속 판정한다.
#: ⚠️ 표지 «끝 자리»에서 이어 붙여 본다(re.Pattern.match(text, pos)). 조사·인용
#:    어미와 판단 동사구 한 마디(「…라고 볼 근거는 없다」)까지만 건너뛰므로,
#:    뒤 절의 무관한 부정으로 긍정 단언을 놓치지 않는다. 이 닫힌 꼴 밖의 부정은
#:    여전히 «단언»으로 보고 관계 근거를 요구한다 — 남은 판단은 의미 검수의 몫이다.
CLAIM_CAUSE_NEGATED_RE: Final[re.Pattern[str]] = re.compile(
    r"(?:이|가|은|는|도|만|라고|이라고|라|으로|로)*\s*"
    r"(?:(?:볼|말할|단정할|판단할|보기|말하기|단정하기|판단하기)\s*"
    r"(?:수|근거|이유)?\s*(?:은|는|가|도)?\s*)?"
    r"(?:아니|아닙|아닌|아냐|않|없|"
    r"(?:보|말하|단정하|판단하|평가하)기\s*(?:는|가|도)?\s*(?:어렵|힘들|무리))"
)
#: 검수 응답의 관계 항목 키. 기존 검증근거 배열과 같은 자리에 놓는다.
RELATION_KEY: Final[str] = "관계"
RELATION_SOURCE_KEY: Final[str] = "근거"
RELATION_QUOTE_KEY: Final[str] = "원문"
RELATION_TYPE_KEY: Final[str] = "유형"
#: 관계 유형의 닫힌 목록. 이 밖의 값은 받지 않는다.
RELATION_CAUSAL: Final[str] = "인과"
RELATION_CONCESSIVE: Final[str] = "양보"
RELATION_TYPES: Final[tuple[str, ...]] = (
    RELATION_CAUSAL, RELATION_CONCESSIVE, "역할", "과금",
)
#: 관계 항목이 «무엇이 원인이고 무엇이 결과인지»를 스스로 밝히게 하는 칸.
#:
#: ★ 이것이 없으면 「인과 낱말 + verbatim 포함」만으로 통과한다. 같은 출처의
#:   무관한 인과 문장을 대거나(ROOT 반례 1), 그 관계를 «부정»한 문장을 대도
#:   (ROOT 반례 2) 막히지 않았다. 원인·결과를 명시하게 해야 «그 후보의 관계»에
#:   결속된다.
RELATION_CAUSE_KEY: Final[str] = "원인"
RELATION_EFFECT_KEY: Final[str] = "결과"
#: 변화의 «방향»만 가리키는 낱말. 원인·결과 칸이 이 낱말 하나로만 채워지면
#: «무엇이» 변했는지가 빠져서 서로 다른 대상의 증감이 같은 관계로 붙는다.
#:
#: ★ 실측 반례: 후보 「비용 감소가 이익 증가의 주요 원인이다」에 원문
#:   「수요 감소가 비용 증가의 주요 원인이다」를 대고 원인=「감소」·결과=「증가」로
#:   적으면, 두 칸이 후보에도 원문에도 글자로 들어 있어 모든 검사를 통과했다.
DIRECTION_ONLY_WORDS: Final[tuple[str, ...]] = (
    "증가", "감소", "상승", "하락", "확대", "축소", "성장", "둔화", "개선", "악화",
    "증대", "감축", "호전", "부진", "위축", "반등", "급증", "급감", "증진",
    "상향", "하향", "회복", "정체",
)
#: 칸 «전체»가 방향 낱말 하나(와 그 파생 어미)뿐일 때만 걸린다. 「비용 감소」·
#: 「이익 증가」처럼 무엇이 변했는지가 붙은 값은 그대로 통과한다.
#: ⚠️ 길이·유사도 문턱이 아니라 «닫힌 목록 + 전체 일치»다. 목록 밖 표현은
#:    이 규칙이 아무 판정도 하지 않는다.
SLOT_DIRECTION_ONLY_RE: Final[re.Pattern[str]] = re.compile(
    r"\A(?:" + "|".join(DIRECTION_ONLY_WORDS) + r")"
    r"(?:세|폭|율|률|추세)?(?:하|되|시키)?(?:다|한|된|됨|함|하는|되는)?\Z"
)
#: 원문에서 «누가 원인이고 누가 결과인지»를 문법으로 표시하는 구문 틀.
#:
#: ★ 글자 순서로 방향을 정하면 틀린다 — 「이익 증가는 비용 감소가 주요 원인이다」처럼
#:   결과가 먼저 오는 정상 문장이 많다(ROOT 지적). 그래서 순서가 아니라 «역할 표지가
#:   어느 쪽에 붙어 있는가»를 본다. 각 틀은 공백을 지운 표면형에 대해 검사하며,
#:   {cause}·{effect} 자리에 후보가 선언한 원인·결과를 그대로 끼워 넣는다.
#: ⚠️ 여기 없는 표현은 «관계를 증명하지 못함»으로 남는다. 통과가 아니라 미증명이다.
#: 후보 표지(CLAIM_CAUSE_RE)와 «같은» 닫힌 수식어를 역할 틀도 쓴다. 한쪽만 늘리면
#: 「가장 큰 원인」처럼 단언으로는 세면서 역할은 못 세는 어긋남이 생긴다.
#: ⚠️ 틀은 공백을 지운 표면형에 대해 검사하므로 여기서는 「가장큰」으로 적는다.
CAUSE_QUALIFIER: Final[str] = r"(?:주요|주된|핵심|가장큰)?"
CAUSAL_ROLE_TEMPLATES: Final[tuple[str, ...]] = (
    r"{cause}(으로|로)인(해|한|하여)[^;.]*?{effect}",
    r"{cause}때문[^;.]*?{effect}",
    r"{cause}에힘입어[^;.]*?{effect}",
    r"{cause}덕분[^;.]*?{effect}",
    r"{effect}(은|는|이|가)[^;.]*?{cause}(이|가)" + CAUSE_QUALIFIER + r"(원인|배경|요인)",
    r"{cause}(은|는|이|가)[^;.]*?{effect}(의)" + CAUSE_QUALIFIER + r"(원인|배경|요인)",
    r"{effect}(의)" + CAUSE_QUALIFIER + r"(원인|배경|요인)[^;.]*?{cause}",
    r"{cause}[^;.]*?{effect}(을|를)(견인|이끌|초래|야기)",
)
#: 도식 후보 문자열을 만들 때 칸을 잇는 문자열. 가드는 이 값으로 칸 경계를
#: 되찾는다 — 후보를 만든 쪽과 어긋나면 분할 근거가 성립하지 않아 «막히는» 쪽으로
#: 실패한다(조용히 통과하지 않는다).
FLOW_CELL_JOIN: Final[str] = " ; "
#: 구조가 있는 도식에서만 인정하는 «닫힌 분할 꼴» — 결과 칸의 대상·술어 연결.
#:
#: ★ 왜 도식만인가 — prose 에서 절을 넘는 연결을 허용하면 세미콜론으로 이어 붙인
#:   무관한 두 절이 한 관계가 된다. 도식은 «칸»이 실제 구조라, 칸 경계를 문자열이
#:   아니라 별도 입력으로 받아 그 경계에서만 읽을 수 있다.
#: ★ 인정 조건 — 한 칸 «전체»가 그 원인이고, 빈 칸을 뺀 바로 다음 칸 «전체»가
#:   그 결과에 관계 표지를 붙인 꼴이어야 한다. 내용 있는 칸을 건너뛰지는 않는다.
#: ⚠️ 부분 일치·떨어진 칸·역방향은 이 꼴이 아니다. 방향은 원문 쪽 역할 표지가
#:    다시 확인하므로, 후보 구조만으로 인과가 인정되지는 않는다.
SPLIT_EFFECT_CELL_TEMPLATE: Final[str] = (
    r"{effect}(의)" + CAUSE_QUALIFIER + r"(원인|배경|요인)(이다|이며|이었다|임)?"
)
#: 절 경계. 관계 구문이 걸린 «그 절» 안에서만 부정을 찾는다 — 뒤에 이어지는
#: 다른 독립절의 부정(「…; 임금 감소는 없었다」)으로 정상 인과를 지우지 않는다.
CLAUSE_BOUNDARY_RE: Final[re.Pattern[str]] = re.compile(r"[;.]")
#: 원문 문장이 그 관계를 부정하는 표지. 구절을 부정 직전까지만 잘라 내는 우회를
#: 막으려고 «구절이 아니라 구절이 속한 원문 문장»에서 찾는다.
#:
#: ⚠️ 한글은 받침이 다음 음절로 붙는다 — 「아닙니다」에는 「아니」가 «없다».
#:    활용형을 그대로 적어야 한다(실측으로 확인한 첫 판의 구멍).
SOURCE_NEGATION_RE: Final[re.Pattern[str]] = re.compile(
    r"아니|아닙|아닌|아냐|않|없|못하|무관|무방"
)
#: 원문이 그 관계를 «단정하지 않고 물리는» 완곡 부정. 「원인이라고 보기(는)
#: 어렵다」가 실측 반례다.
#:
#: ⚠️ 「어렵다」를 어휘 블랙리스트로 넣으면 「업무가 어렵다」·「원인 규명에
#:    어려움」 같은 정상 실적 문장까지 지운다. 그래서 낱말이 아니라 «판단 동사의
#:    -기 꼴에 곧바로 붙은 경우»만 본다 — 관계를 말하는 그 자리에 붙은 유보다.
SOURCE_HEDGED_NEGATION_RE: Final[re.Pattern[str]] = re.compile(
    r"(?:보|말하|단정하|판단하|평가하)기\s*(?:는|가|도)?\s*(?:어렵|힘들|무리)"
)
#: 원문을 문장 단위로 나누는 기준. 한국어 종결 어미 뒤 구두점에서만 자른다.
SOURCE_SENTENCE_SPLIT_RE: Final[re.Pattern[str]] = re.compile(r"(?<=[다요])[.!?]\s*")
#: 후보가 인과라고 적은 관계의 «원문»이 실제로 인과여야 한다는 표지.
#: ★ 후보 표지·역할 틀이 「원인·배경·요인」을 모두 인과로 세므로 이 사전 검사도
#:   같은 세 낱말을 쓴다. 한쪽만 좁으면 정상 문장 「A가 B의 주요 배경이다」가
#:   비인과로 떨어진다. 여기서 통과해도 역할 틀이 다시 확인하므로 넓어지지 않는다.
SOURCE_CAUSAL_RE: Final[re.Pattern[str]] = re.compile(
    r"원인|배경|요인|때문|기인|견인|이끌|힘입어|영향으로|에\s*따라|로\s*인한|으로\s*인한|로\s*인해|으로\s*인해"
)
#: 그 «원문»이 오히려 양보라면 인과로 받아들이지 않는다.
SOURCE_CONCESSIVE_RE: Final[re.Pattern[str]] = re.compile(r"에도\s*불구하고|그럼에도")

