"""인물명에 붙은 등기임원 직함이 «지금도 유효한가»만 좁게 보는 상수.

기존 근거 검증은 문장이 인용 원문과 «같은 말을 하는가»만 본다. 그래서 원문이
사실이었던 시점(보도 시점)과 후보가 그 사실을 쓰는 시점(보고서 기준일)이 다를 때
생기는 어긋남은 어느 단계에서도 걸러지지 않았다. 실제 사례(멀티캠퍼스, 실행
979d5e3f3cdd68ad4f4249c4bca3adef, 기준일 2026-09-10): 2025-11-18 기사를 그대로
옮긴 「대표이사 정석목」이 본문(7장)에 남았는데, 같은 회사의 사업보고서 정정
(2026-03-16)에는 정석목이 해임 대상자로 공시돼 있었다. 다만 그 두 사실은 «같은
인용 조각»이 아니었다 — 이 가드는 «같은 조각 안»의 어긋남만 잡는다. 조각이 아예
갈려 있던 근본 원인은 조사 보고서에 따로 적었다.

지키는 선(다른 가드와 같다 — role_binding.py·direct_support.py 참고):
  · 유사도 문턱·회사명·인물별 특칙을 쓰지 않는다. 등기임원 직함의 닫힌 목록과
    문자열 인접·포함만 본다.
  · 표지가 없으면 아무 판정도 하지 않는다 — 정상적으로 재직 중인 임원을 소개하는
    문장을 이 검사로 막지 않는다.
  · 그 인물이 «같은 후보가 인용한 원문 조각 안에서» 해임·사임·퇴임·임기만료로
    적혀 있을 때만 발동한다. 인용하지 않은 다른 조각의 근거는 쓰지 않는다 —
    다른 후보·다른 장의 근거를 빌릴 수 없다는 경계는 role_binding.py와 같다.

⚠️ 닫힌 검증이다. 아래는 이 가드가 «확인하지 못한다» — 통과가 아니라 미확인이다:
   후보가 인용하지 않은 다른 조각(예: 별도 공시)에만 있는 해임·사임 기록,
   한글 2~4음절이 아닌 표기(영문·가운뎃점·괄호로 끊긴 이름), 동명이인,
   표(cells)에서 이름과 직함이 서로 다른 칸에 떨어져 있는 경우, 형태소 분석 없이
   판단하므로 이름이 다른 낱말의 일부로 우연히 걸치는 자리.
"""

from __future__ import annotations

from typing import Final

import re

#: 등기임원 직함의 닫힌 목록. 「이사」·「대표」처럼 혼자 쓰이면 「대표전화」·
#: 「이사장」 같은 무관한 말까지 걸리므로 완결된 직함만 둔다. 겹치는 접두 표현은
#: «긴 것 먼저» 두어야 정규식 교대(|)가 짧은 쪽에서 먼저 끊지 않는다
#: (「감사위원」이 「감사」보다 먼저 와야 「감사위원」이 「감사」+「위원」으로
#: 잘리지 않는다).
EXECUTIVE_TITLE_WORDS: Final[tuple[str, ...]] = (
    "각자대표이사", "공동대표이사", "대표이사",
    "기타비상무이사", "사내이사", "사외이사",
    "감사위원", "감사",
)

#: 그 직함에서 이미 물러났다는 뜻의 닫힌 표지. 「중도퇴임」은 「퇴임」에 걸린다.
STATUS_DEPARTURE_WORDS: Final[tuple[str, ...]] = ("해임", "사임", "퇴임", "임기만료")

#: 같은 인물이 다시 그 자리로 돌아왔다는 뜻의 닫힌 표지. 같은 원문 조각 안에 이
#: 표지가 함께 있으면(순서·시점과 무관하게) 이 가드는 판단을 보류한다 — 재선임
#: 이후 시점인지 이 가드는 확인할 수 없기 때문이다(보류가 안전한 쪽이다).
STATUS_REAPPOINTMENT_WORDS: Final[tuple[str, ...]] = ("재선임", "재선출", "연임")

#: 이름 자리로 인정하는 표면형 — 한글 2~4음절. 그 밖의 표기(영문·로마자·가운뎃점
#: 낀 이름)는 이 닫힌 꼴 밖이라 다루지 않는다(확인하지 못함으로 남긴다).
_NAME_RE: Final[str] = r"[가-힣]{2,4}"

#: 이름 뒤에 흔히 붙는 조사 한 글자. 탐욕적 정규식이 이름 뒤 조사까지 삼켰을 때
#: («정석목이»처럼) 되돌리는 용도로만 쓴다 — 이름의 일부로 취급하지 않는다.
TRAILING_PARTICLE_CHARS: Final[str] = "이가은는을를의도과와만"


def _title_name_patterns(titles: tuple[str, ...]) -> tuple[re.Pattern[str], ...]:
    """「직함 이름」·「이름 직함」 두 어순을 모두 잡는 닫힌 정규식을 만든다."""

    alt = "|".join(re.escape(title) for title in titles)
    return (
        re.compile(r"(?:" + alt + r")\s?(" + _NAME_RE + r")"),
        re.compile(r"(" + _NAME_RE + r")\s?(?:" + alt + r")"),
    )


#: 「대표이사 정석목」·「정석목 대표이사」 두 어순을 모두 본다. 공백 없이 붙거나
#: 한 칸 띄운 꼴만 인정한다 — 조사·수식어가 낀 자리는 이름 경계를 확정할 수 없어
#: 다루지 않는다(확인하지 못함으로 남긴다).
TITLE_NAME_PATTERNS: Final[tuple[re.Pattern[str], ...]] = _title_name_patterns(
    EXECUTIVE_TITLE_WORDS
)

#: 이름 좌우 «가까운 자리»에서만 이탈 표지를 찾는다. 창을 너무 넓히면 표 안의
#: 다른 인물의 해임 기록을 이 이름의 것으로 잘못 묶는다(표는 인물이 여럿이다).
STATUS_WINDOW_CHARS: Final[int] = 40

#: 이탈 표지 가까이서 날짜를 찾는 닫힌 꼴. 「2026년 03월 18일」·「2026-03-18」·
#: 「2026.03.18」만 인정한다 — 「올해 3월」처럼 닫힌 숫자 꼴이 아닌 표기는
#: 다루지 않는다.
