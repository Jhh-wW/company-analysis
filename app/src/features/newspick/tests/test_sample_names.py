"""표본 인명 위생 시험 — 공개 저장소에 실존 인물 이름을 두지 않는다.

`newspick`은 대표자 «이름»으로 기사를 찾는 기능이라 시험 표본이 사람 이름이다.
그 표본을 전자공시에서 받아온 이름 그대로 적어 두면 실존 임원 이름이 공개
저장소에 남는다. 개인정보를 올리지 않는다는 제품 원칙에 걸린다.

★ 이 시험은 «지운 이름 목록»을 적지 않는다. 적으면 지운 이름이 그대로
  되돌아오기 때문이다. 대신 «표본은 승인된 가명만 쓴다»를 확인한다.
  그래서 지금 지운 이름뿐 아니라 앞으로 들어올 어떤 실명도 함께 막는다.
"""

from __future__ import annotations

import pathlib
import re


#: 표본에 써도 되는 한글 토막. 가명은 성씨 + 「대표」라 한눈에 가짜임이 보인다.
#: 「홍길동」은 오래 쓰인 가상 인물이고, 「가나·다라·마바·사아」는 외국식
#: 여러 토막 이름의 «꼴»만 흉내 낸 것이다. 나머지는 괄호 안 직함 낱말이다.
_허용_토막 = frozenset(
    {
        "김대표", "이대표", "박대표", "최대표", "정대표",
        "강대표", "조대표", "윤대표", "한대표", "오대표", "서대표",
        "홍길동",
        "가나", "다라", "마바", "사아",
        "각자", "대표이사", "각자대표이사", "전각괄호",
        # 「하이브 대표 인터뷰」는 «이름 없이 검색하면 잡음이 크다»는 반례로
        # 주석에 남아 있다. 사람 이름이 아니라 낱말이므로 허용한다.
        "대표",
    }
)

#: ① 대표자 값을 바로 넣는 자리 — `{"ceo_nm": "…"}`
_CEO_NM = re.compile(r'ceo_nm"?\s*[:=]\s*"([^"]*)"')

#: ② `ceo_name` 검사표 — 파일 안에 표시해 둔 두 줄 사이만 본다.
#:    표시가 없으면 시험이 조용히 통과하지 않도록 아래에서 존재를 단정한다.
_표본_시작 = "── 대표자 표본 시작 ──"
_표본_끝 = "── 대표자 표본 끝 ──"
_짝 = re.compile(r'\(\s*"([^"]*)",\s*"([^"]*)"\s*\)')

#: ③ 주석에 적힌 검색어 예시 — 「회사 이름 인터뷰」꼴에 사람 이름이 들어간다.
_검색어_예시 = re.compile(r"「\s*[가-힣A-Za-z]+\s+([가-힣]{2,4})\s+(?:인터뷰|전략)")

#: ④ 설명글에 적힌 공동대표 예시 — 「이름, 이름」꼴.
_공동대표_예시 = re.compile(r"「\s*([가-힣]{2,4}),\s*([가-힣]{2,4})\s*」")

#: 표본을 하나도 못 찾으면 시험이 «조용히 통과»한다 — 그걸 막는 바닥선.
_MIN_표본 = 15

_대상 = ("constants.py", "logic.py", "tests/test_logic.py")


def _feature_root() -> pathlib.Path:
    return pathlib.Path(__file__).resolve().parent.parent


def _검사표_구간(본문: str) -> str:
    """표시해 둔 두 줄 사이의 검사표만 잘라 낸다. 표시가 없으면 빈 문자열."""
    시작 = 본문.find(_표본_시작)
    끝 = 본문.find(_표본_끝)
    if 시작 == -1 or 끝 == -1 or 끝 < 시작:
        return ""
    return 본문[시작:끝]


def _표본들() -> list[tuple[str, str]]:
    """대표자 이름이 적히는 «자리»에서만 값을 모은다. (파일명, 값)"""
    뿌리 = _feature_root()
    모음: list[tuple[str, str]] = []
    for 이름 in _대상:
        path = 뿌리 / 이름
        if not path.exists():
            continue
        본문 = path.read_text(encoding="utf-8")
        for m in _CEO_NM.finditer(본문):
            모음.append((이름, m.group(1)))
        for m in _짝.finditer(_검사표_구간(본문)):
            모음.append((이름, m.group(1)))
            모음.append((이름, m.group(2)))
        for m in _검색어_예시.finditer(본문):
            모음.append((이름, m.group(1)))
        for m in _공동대표_예시.finditer(본문):
            모음.append((이름, m.group(1)))
            모음.append((이름, m.group(2)))
    return 모음


def test_newspick_표본에_실존_인명이_없다():
    """★ 대표자 표본은 승인된 가명만 쓴다 (제품 원칙: 개인정보 비공개)."""
    검사표 = _검사표_구간(
        (_feature_root() / "tests" / "test_logic.py").read_text(encoding="utf-8")
    )
    assert 검사표, (
        f"검사표 표시({_표본_시작} … {_표본_끝})를 못 찾았습니다 — "
        "표시를 지우면 이 시험이 아무것도 안 보고 통과합니다"
    )

    표본 = _표본들()
    assert len(표본) >= _MIN_표본, (
        f"표본을 {len(표본)}개밖에 못 찾았습니다 — 자리를 못 읽었을 수 있습니다"
    )

    걸린것: list[str] = []
    for 파일, 값 in 표본:
        for 토막 in re.findall(r"[가-힣]+", 값):
            if 토막 not in _허용_토막:
                걸린것.append(f"{파일}: {토막}")
    assert not 걸린것, (
        "승인되지 않은 한글 이름이 대표자 표본 자리에 있습니다 — 가명으로 "
        f"바꾸세요: {sorted(set(걸린것))}"
    )
