#: 새로 뜰 절 — {조각 종류: (찾을 표제들…)}.
#: ★ 표제는 «여러 개» 둔다. 회사마다 표기가 다르다.
#: ⚠️ 늘릴 때마다 실측으로 «무엇이 실제로 뜨는지» 확인할 것 —
