def test_지적재산권_표의_출원일_등록일_현재상태_열이_살아서_온다() -> None:
    """★ 「등록일이 비어 있고 상태가 출원완료인 행」을 뽑으려면 이 열들이 있어야 한다.

    실측 — ㈜진영 사업보고서가 정확히 이 모양이었다.
    날짜(2004.08.30)는 금액꼴(1,234)이 아니라 표 판정에 안 걸린다.
    """
    원문 = _긴문장(
        "주요 지적재산권 보유 현황",
        "번호 구분 내용 권리자 출원일 등록일 적용제품 출원국 현재상태 "
        "1 특허권 가구용 엣지 몰딩재 2004.08.30 2005.08.25 엣지 대한민국 등록 "
        "2 상표권 세이프코트 2024.03.11 출원완료",
    )

    덩어리 = find_section(원문, EXTRA_SECTION_HEADS["지적재산권"], DEFAULT_FRAG_CHARS)

    assert "출원일" in 덩어리
    assert "등록일" in 덩어리
    assert "현재상태" in 덩어리
    assert "출원완료" in 덩어리


