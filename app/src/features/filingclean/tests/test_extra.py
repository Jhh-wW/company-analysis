def test_표로_시작하면_건너뛴다() -> None:
    """숫자 나열은 자소서에 못 쓴다 — 앞 400자에 금액꼴 숫자가 6개 이상이면 표로 본다."""
    표 = "시장점유율 " + " ".join(f"{i},{i}{i}{i}" for i in range(1, 12)) + " " + "가 " * 200

