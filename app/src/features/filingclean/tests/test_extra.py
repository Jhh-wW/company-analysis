def test_못_찾은_절은_아예_안_담는다() -> None:
    """★ 빈 조각이 들어가면 「재료가 있는데 안 쓰였다」로 잘못 읽힌다."""
    원문 = _긴문장("핵심감사사항", "감사인은 재고자산의 평가를 핵심감사사항으로 결정하였습니다.")

    모은것 = collect(원문)

    assert "감사인지적" in 모은것
    assert "지적재산권" not in 모은것
    assert all(v for v in 모은것.values()), "빈 문자열이 담겼다"


def test_원문이_비면_아무것도_안_모은다() -> None:
    assert collect("") == {}


def test_1판이_이미_뜬_종류는_덮어쓰지_않는다() -> None:
    """★ 1판은 0줄 고치지 않는다 — 더할 뿐이다."""
    원문 = _긴문장("핵심감사사항", "감사인은 재고자산의 평가를 핵심감사사항으로 결정하였습니다.")
    있던것 = {1: {"종류": "감사인지적", "원문": "1판이 먼저 뜬 것"}}

    합친것, 더함 = add_to(있던것, 원문)

    assert 더함 == 0
    assert 합친것[1]["원문"] == "1판이 먼저 뜬 것"


def test_새_절은_빈_번호부터_이어_붙인다() -> None:
    원문 = _긴문장("핵심감사사항", "감사인은 재고자산의 평가를 핵심감사사항으로 결정하였습니다.")
    있던것 = {1: {"종류": "사업내용", "원문": "가" * 300}, 7: {"종류": "재무", "원문": "나" * 300}}

    합친것, 더함 = add_to(있던것, 원문)

    assert 더함 == 1
    assert 합친것[1]["원문"].startswith("가")
    assert 합친것[7]["원문"].startswith("나")
    assert 합친것[8]["종류"] == "감사인지적"


def test_원본_조각을_바꾸지_않는다() -> None:
    """★ 원본을 바꾸면 부르는 쪽이 「더하기 전」 상태를 다시 볼 수 없다."""
    원문 = _긴문장("핵심감사사항", "감사인은 재고자산의 평가를 핵심감사사항으로 결정하였습니다.")
    있던것 = {1: {"종류": "사업내용", "원문": "가" * 300}}

    합친것, _ = add_to(있던것, 원문)

    assert len(있던것) == 1
    assert len(합친것) == 2
