"""1판이 «안 뜨는» 절을 더 모으는 규칙을 못 박는다 (`filingclean/extra.py`).

★ 왜 이 파일이 생겼나
  ─────────────────────────────────────────────────────────
  `extra.py` 는 228줄인데 **그 파일을 지키는 시험이 저장소에 0건**이었다.
  표제를 지우거나 표 판정 기준을 바꿔도 아무 데도 빨간불이 안 떴다는 뜻이다.
  오늘 같은 종류의 구멍을 세 번째로 만났다(`ceo_name`·`_AUTH_STATUSES`·여기).

★ 이 규칙이 왜 중요한가
  ─────────────────────────────────────────────────────────
  공시 원문은 **본문만 16만~71만 자**인데 1판이 뜨는 것은 8종류 × 1,200자뿐이다.
  즉 원문의 **6% 미만만 쓰고 버린다.** 이 파일이 그 버려진 곳에서 절을 더 건진다.
  표제 하나가 사라지면 그 절을 재료로 삼는 장이 **조용히 빈다** — 화면에는
  「자료가 없습니다」로 보이는데 실제로는 원문에 있었던 것이다.

★ 시험에 쓴 문구는 **실제 공시 원문 2건**
  (㈜진영 사업보고서 본문 167,830자 · 다른 대기업 사업보고서 본문 715,332자)에서
  «모양을 확인한 뒤» 그 모양대로 짧게 다시 쓴 것이다. 원문을 통째로 옮기지 않았다.
"""

from __future__ import annotations

import pytest

from src.features.filingclean.extra import (
    DEFAULT_FRAG_CHARS,
    EXTRA_SECTION_HEADS,
    MIN_CHUNK_CHARS,
    NAME_TABLE_MAX_FRAG_CHARS,
    add_to,
    collect,
    find_section,
)


def _긴문장(머리: str, 본문: str) -> str:
    """조각으로 인정받을 만큼(200자 초과) 긴 절 하나를 만든다."""
    return 머리 + " " + (본문 + " ") * 12


