def test_목차는_건너뛰고_다음_출현을_쓴다() -> None:
    """★ 사업보고서 첫 장이 목차라, 첫 출현을 그대로 뜨면 통째로 목차가 된다 (P-99)."""
    목차 = "핵심감사사항 " + " ".join(f"{i}. 항목 ........ {i}" for i in range(1, 40))
    본문 = _긴문장("핵심감사사항", "감사인은 재고자산의 평가를 핵심감사사항으로 결정하였습니다.")

    덩어리 = find_section(목차 + " " + 본문, EXTRA_SECTION_HEADS["감사인지적"], DEFAULT_FRAG_CHARS)

    assert "재고자산의 평가" in 덩어리


def test_표로_시작하면_건너뛴다() -> None:
    """숫자 나열은 자소서에 못 쓴다 — 앞 400자에 금액꼴 숫자가 6개 이상이면 표로 본다."""
    표 = "시장점유율 " + " ".join(f"{i},{i}{i}{i}" for i in range(1, 12)) + " " + "가 " * 200

    덩어리 = find_section(표, EXTRA_SECTION_HEADS["시장점유율"], DEFAULT_FRAG_CHARS)

    assert 덩어리 == ""


def test_너무_짧으면_조각으로_안_친다() -> None:
    """200자 이하는 문장 하나도 못 건진다."""
    짧음 = "핵심감사사항 " + "가" * (MIN_CHUNK_CHARS - 20)

    assert find_section(짧음, EXTRA_SECTION_HEADS["감사인지적"], DEFAULT_FRAG_CHARS) == ""


def test_표제가_아예_없으면_빈_문자열이다() -> None:
    assert find_section("아무 상관 없는 글 " * 50, EXTRA_SECTION_HEADS["지적재산권"], DEFAULT_FRAG_CHARS) == ""


