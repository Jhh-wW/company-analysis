def test_카카오형_제품서비스_브랜드표는_숫자가_많아도_다음_표제까지_뜬다() -> None:
    행들 = " ".join(
        f"브랜드{i} 플랫폼서비스{i} {i * 1_000:,} {i * 2_000:,} {i * 3_000:,}"
        for i in range(1, 36)
    )
    원문 = (
        "2. 주요 제품 및 서비스 가. 주요 제품 및 서비스 현황 "
        f"브랜드 서비스 매출액 {행들} "
        "나. 주요 제품 등의 가격변동 추이 뒤 절의 내용은 조각에 들어가면 안 됩니다."
    )

    덩어리 = collect(원문)["제품서비스"]

    assert "브랜드35" in 덩어리
    assert "1,000" in 덩어리
    assert len(덩어리) > DEFAULT_FRAG_CHARS
    assert len(덩어리) <= NAME_TABLE_MAX_FRAG_CHARS
    assert "가격변동 추이" not in 덩어리


def test_우리은행형_상품내용_2열표가_종류를_지킨_조각으로_추가된다() -> None:
    행들 = " ".join(
        f"상품명{i} 기업고객의 자금 운용과 결제를 지원하는 금융 서비스 {i * 12_345:,}"
        for i in range(1, 10)
    )
    원문 = (
        "다. 주요 상품 및 서비스의 내용 상품명 주요 내용 "
        f"{행들} 라. 주요 영업설비 현황 다음 절입니다."
    )

    합친것, 더함 = add_to({}, 원문)

    assert 더함 == 1
    assert 합친것[1]["종류"] == "상품내용"
    assert "상품명9" in 합친것[1]["원문"]
    assert "영업설비 현황" not in 합친것[1]["원문"]


