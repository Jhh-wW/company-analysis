# -*- coding: utf-8 -*-
"""1판이 «안 뜨는» 절을 더 모으는 규칙을 못 박는다 (`filingclean/extra.py`).

★ 왜 이 파일이 생겼나 (2026-08-27)
  ─────────────────────────────────────────────────────────
  `extra.py` 는 228줄인데 **그 파일을 지키는 시험이 저장소에 0건**이었다.
  표제를 지우거나 표 판정 기준을 바꿔도 아무 데도 빨간불이 안 떴다는 뜻이다.
  오늘 같은 종류의 구멍을 세 번째로 만났다(`ceo_name`·`_AUTH_STATUSES`·여기).

★ 이 규칙이 왜 중요한가
  ─────────────────────────────────────────────────────────
  공시 원문은 **본문만 16만~71만 자**인데 1판이 뜨는 것은 8종류 × 1,200자뿐이다.
  즉 원문의 **6% 미만만 쓰고 버린다.** 이 파일이 그 버려진 곳에서 절을 더 건진다.
  표제 하나가 사라지면 그 절을 재료로 삼는 장이 **조용히 빈다** — 화면에는
  「자료가 없습니다」로 보이는데 실제로는 원문에 있었던 것이다.

★ 시험에 쓴 문구는 **2026-08-27에 실제 공시 원문 2건**
  (㈜진영 사업보고서 본문 167,830자 · 다른 대기업 사업보고서 본문 715,332자)에서
  «모양을 확인한 뒤» 그 모양대로 짧게 다시 쓴 것이다. 원문을 통째로 옮기지 않았다.
"""

from __future__ import annotations

import pytest

from src.features.filingclean.extra import (
    DEFAULT_FRAG_CHARS,
    EXTRA_SECTION_HEADS,
    MIN_CHUNK_CHARS,
    add_to,
    collect,
    find_section,
)


def _긴문장(머리: str, 본문: str) -> str:
    """조각으로 인정받을 만큼(200자 초과) 긴 절 하나를 만든다."""
    return 머리 + " " + (본문 + " ") * 12


# ══════════════════════════════════════════════════════════
# 목록 자체 — 절을 지우면 여기서 걸린다
# ══════════════════════════════════════════════════════════


@pytest.mark.parametrize(
    "종류",
    ["신규사업전망", "시장점유율", "소송·분쟁", "감사인지적", "지적재산권", "위험요인"],
)
def test_더_모으기로_한_절이_목록에_남아_있다(종류: str) -> None:
    """★ 절을 지우면 그 재료를 쓰던 장이 조용히 빈다. 지우려면 이 시험을 먼저 고쳐라."""
    assert 종류 in EXTRA_SECTION_HEADS
    assert EXTRA_SECTION_HEADS[종류], f"{종류}: 표제 후보가 비었다"


def test_감사인지적은_핵심감사사항을_첫_후보로_둔다() -> None:
    """가장 값진 표제를 앞에 둔다 — `find_section`이 앞 후보부터 찾기 때문이다."""
    assert EXTRA_SECTION_HEADS["감사인지적"][0] == "핵심감사사항"


def test_회계감사인의_명칭_및_감사의견은_일부러_안_넣는다() -> None:
    """★ 그 표제는 곧바로 감사인·의견 «표»로 이어져 지원동기에 쓸 문장이 안 나온다.

    실측 — 그 자리에서 뜨는 것은 「한미회계법인 적정의견」뿐이었다.
    넣고 싶어지면 먼저 실제 공시로 «문장이 나오는지» 재라.
    """
    모든표제 = [h for heads in EXTRA_SECTION_HEADS.values() for h in heads]
    assert "회계감사인의 명칭 및 감사의견" not in 모든표제


def test_산업재산권은_일부러_안_넣는다() -> None:
    """★ 그 표제는 «회계 주석»(무형자산 장부금액)을 물어온다.

    실측 (2026-08-27, 회사 20곳 사업보고서 직접 조회) — 「산업재산권」으로 뜬 8곳이
    전부 숫자 표였다:
      삼성전자 「산업재산권 회원권 기타 … 4,789,366 272,898 …」
      NAVER   「산업재산권 장부금액 취득원가 11,951,314 …」
    지원동기에 쓸 것이 하나도 없다. 넣고 싶어지면 먼저 실제 공시로 다시 재라.
    """
    모든표제 = [h for heads in EXTRA_SECTION_HEADS.values() for h in heads]
    assert "산업재산권" not in 모든표제


def test_회계_주석이_지적재산권_절로_잡히지_않는다() -> None:
    """★ 무형자산 장부금액 표가 재료로 들어오면 3장이 숫자 나열로 오염된다."""
    회계주석 = _긴문장(
        "산업재산권",
        "회원권 기타 기초의 무형자산 및 영업권 4,789,366 272,898 11,507,761 7,168,541 23,738,566",
    )

    assert find_section(회계주석, EXTRA_SECTION_HEADS["지적재산권"], DEFAULT_FRAG_CHARS) == ""


