"""공식 원문 산문 숫자 토큰화·대조(ADR 0005) — 모듈 단위 시험.

기대값은 전부 리터럴이다. 예시 문장·숫자는 합성이다.
"""

from __future__ import annotations

import pytest

from src.shared.report_quality.official_prose_numeric import (
    official_number_tokens,
    prose_numbers_verbatim_in_fragments,
)


@pytest.mark.parametrize(
    ("text", "tokens"),
    [
        # 총괄이 정한 예시
        ("3억 원", {"3억원"}),
        ("2025년 3월", {"2025년", "3월"}),
        ("12.5%", {"12.5%"}),
        ("1,234명", {"1234명"}),
        # 크기어 묶음·띄어 쓴 단위
        ("3억원", {"3억원"}),
        ("1조 2천억 원", {"1조2천억원"}),
        ("5만 명", {"5만명"}),
        ("100만 명의 고객", {"100만명"}),
        ("12.5 %", {"12.5%"}),
        ("3 원래", {"3"}),
        # 백분율 뒤 글자·붙은 낱말 전체가 단위
        ("3%p", {"3%p"}),
        ("3%포인트", {"3%포인트"}),
        ("3개국", {"3개국"}),
        ("3개월", {"3개월"}),
        ("3세대", {"3세대"}),
        # 조사·어림 꼬리만 지운다
        ("12개의", {"12개"}),
        ("2019년부터", {"2019년"}),
        ("1위를", {"1위"}),
        ("3월께", {"3월"}),
        # 값을 바꾸지 않는 시간 꼬리는 앞 단위로 읽는다(뜻이 바뀌는 꼬리는 그대로)
        ("10년간", {"10년"}),
        ("15일자로", {"15일"}),
        ("2023년도", {"2023년"}),
        ("3월말", {"3월"}),
        ("1990년대", {"1990년대"}),
        ("30주년", {"30주년"}),
        # 목록 쉼표는 숫자가 아니다
        ("2019, 2020, 2021년", {"2019", "2020", "2021년"}),
        # 숫자 앞 한글은 넣지 않고, 로마자는 넣는다
        ("제3공장", {"3공장"}),
        ("H100", {"H100"}),
        ("FY2023", {"FY2023"}),
        ("5G", {"5G"}),
        # 날짜 한 덩어리·전각
        ("2019.03.15", {"2019.03.15"}),
        ("２０２１년", {"2021년"}),
        ("５％", {"5%"}),
        # 한글 수량 — 숫자 표현 자리를 비운 글에서만 뽑는다
        ("두 배로 늘었다", {"두배"}),
        ("절반 수준인 2,500억원", {"2500억원", "절반"}),
        ("4천억 원", {"4천억원"}),
        ("천억 원", {"천억원"}),
        # 부호는 토큰 머리다(−·△·▼ → -, ▲ → +). 앞이 숫자·로마자면 붙임표다
        ("-3.5%로", {"-3.5%"}),
        ("△3.5%로", {"-3.5%"}),
        ("▼3%", {"-3%"}),
        ("▲3%", {"+3%"}),
        ("+3%", {"+3%"}),
        ("2019-2021년", {"2019", "2021년"}),
        ("COVID-19", {"19"}),
        # 한 글자 조사가 낱말 전체면 단위로 둔다(맨 숫자로 무너지지 않게)
        ("5도 올랐다", {"5도"}),
        ("종로3가 거리", {"3가"}),
        ("제3과", {"3과"}),
        ("2019부터", {"2019"}),
        # 서술 꼬리는 지운다
        ("12.5%다", {"12.5%"}),
        ("3.5%라고", {"3.5%"}),
        # 기간(«3일간»)은 날짜(«3일»)와 다른 토큰이다
        ("3일간 멈췄다", {"3일간"}),
        # 숫자가 없으면 빈 집합
        ("공식 자료를 공개했다", set()),
        ("", set()),
    ],
)
def test_토큰화_정규화_표(text: str, tokens: set[str]):
    assert official_number_tokens(text) == frozenset(tokens)


def test_None도_빈_집합이다():
    assert official_number_tokens(None) == frozenset()  # type: ignore[arg-type]


def test_숫자_토큰이_없는_문장은_조각이_비어도_참이다():
    assert prose_numbers_verbatim_in_fragments("공식 자료를 공개했다", []) is True
    assert prose_numbers_verbatim_in_fragments("공식 자료를 공개했다", [""]) is True


def test_토큰이_있는데_조각이_없거나_비면_거짓이다():
    assert prose_numbers_verbatim_in_fragments("2019년 설립", []) is False
    assert prose_numbers_verbatim_in_fragments("2019년 설립", [""]) is False
    assert prose_numbers_verbatim_in_fragments("2019년 설립", ["숫자 없는 원문"]) is False


def test_모든_토큰이_조각별_합집합에_있어야_참이다():
    assert prose_numbers_verbatim_in_fragments(
        "2019년 설립, 12개 사업장", ["2019년 설립했다.", "12개 사업장을 운영한다."],
    ) is True
    assert prose_numbers_verbatim_in_fragments(
        "2019년 3월 15일 설립", ["2019년 3월 설립했다."],
    ) is False


def test_조각을_이어_붙이지_않는다():
    """«합계 3» + «개 사업»을 이으면 «3개»가 생긴다 — 조각마다 따로 센다."""

    assert prose_numbers_verbatim_in_fragments("3개 사업", ["합계 3", "개 사업"]) is False
    assert prose_numbers_verbatim_in_fragments("3개 사업", ["합계 3 개 사업"]) is True


def test_문자열_하나를_조각_목록으로_넘기면_거절한다():
    with pytest.raises(TypeError):
        prose_numbers_verbatim_in_fragments(
            "2019년", "2019년 설립",  # type: ignore[arg-type]
        )


@pytest.mark.parametrize(
    ("sentence", "fragment"),
    [
        # 띄어 쓴 크기어를 가르면 통과하던 것(뉴스 토큰화의 반례)
        ("3억 원", "제3공장 … 5억 원"),
        ("1조 2천억 원", "제1·제2공장, 총 4천억 원"),
        ("5만 명", "제5공장 … 3만 명"),
        # 통째 비교 — 부분 일치 금지
        ("12월", "2012년"),
        ("3억원", "13억원"),
        ("1개", "11개"),
        # 한글 수량이 원문에 없다(빈 집합으로 통과하면 안 된다)
        ("두 배로 늘었다", "크게 늘었다"),
        ("절반으로 줄었다", "크게 줄었다"),
        # 한글로만 쓴 크기어가 숫자 표현 안의 조각과 맞지 않는다
        ("천억 원", "4천억 원"),
        # 단위가 다르면 다른 값이다
        ("3개국", "3개월"),
        ("3%p", "3%"),
        # 앞에 글자가 붙은 숫자
        ("H100", "100대"),
        ("3세대", "제3공장"),
        # 부호가 다르면 다른 값이다
        ("이익률은 -3.5%로", "이익률 3.5%로"),
        ("3.5%로", "△3.5%로"),
        ("▲3%", "▼3%"),
        ("+3%", "3%"),
        # 조사와 겹치는 단위·기간 꼬리가 맨 숫자·날짜와 섞이지 않는다
        ("5도 올랐다", "5, 6종"),
        ("3일간 멈췄다", "3월 3일 멈췄다"),
    ],
)
def test_값이나_단위가_다른_숫자는_거짓이다(sentence: str, fragment: str):
    assert prose_numbers_verbatim_in_fragments(sentence, [fragment]) is False


@pytest.mark.parametrize(
    ("sentence", "fragment", "expected"),
    [
        # B1 같은 값의 공백 차이 — 통과
        ("3억 원", "3억원", True),
        # B4 날짜 조합의 우연 일치 — 통과(받아들인 약점, ADR에 적는다)
        ("2021년 3월", "2021년 5월 …, 3월 …", True),
        # B5 목록 뒤 단위 — 거짓 차단(받아들인 약점)
        ("2020년", "2019, 2020, 2021년", False),
        # B7 전각 숫자 — 통과
        ("２０２１년", "2021년", True),
        # B8 같은 숫자 두 번 — 집합으로 본다
        ("2019년과 2019년", "2019년", True),
        # 같은 부호는 표기가 달라도 같은 값이다
        ("△3.5%", "-3.5%", True),
        ("▲3%", "+3%", True),
        # 서술 꼬리만 다르다
        ("12.5%다", "12.5%로", True),
        # 표기를 바꾼 날짜 — 거짓(최소 정규화)
        ("2019년 3월 15일", "2019.03.15", False),
        ("2019년 03월", "2019년 3월", False),
    ],
)
def test_경계_사례의_결과를_고정한다(sentence: str, fragment: str, expected: bool):
    assert prose_numbers_verbatim_in_fragments(sentence, [fragment]) is expected
