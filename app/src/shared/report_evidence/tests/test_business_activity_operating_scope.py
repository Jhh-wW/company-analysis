"""운영 자료에서 명시된 현재 자기사업만 조사 앵커 후보로 인정한다."""

from types import SimpleNamespace
import pytest

from src.shared.report_evidence.business_activity import current_business_item


def fragment(text, slot="operations_partners:operating_role"):
    return SimpleNamespace(text=text, location="0-100", covered_slot_ids=(slot,), source_context_json="")


@pytest.mark.parametrize("text,item", (
    ("당사는 정밀부품을 생산합니다.", "정밀부품"),
    ("회사는 고객에게 법률 자문서비스를 제공합니다.", "법률 자문서비스"),
    ("당사는 디지털 뉴스콘텐츠를 직접 생산 가공하고 있습니다.", "디지털 뉴스콘텐츠"),
    ("당사는 디지털 뉴스콘텐츠를 유통판매하고 있습니다.", "디지털 뉴스콘텐츠"),
    ("당사는 고객사의 디지털 뉴스콘텐츠를 유통판매합니다.", "고객사의 디지털 뉴스콘텐츠"),
    ("콘텐츠 사업이란 기획과 제작, 유통을 통칭하는 것으로 당사는 기사를 중심으로 한 뉴스콘텐츠를 직접 생산 가공하고 있으며, 이를 판매하고 있습니다.", "뉴스콘텐츠"),
))
def test_구체_제공물과_현재_자기생산_관계_보존(text, item):
    assert current_business_item(fragment(text), "가온기업") == item


@pytest.mark.parametrize("text", (
    "콘텐츠 사업이란 기획과 제작, 유통을 통칭하는 것으로 매체는 뉴스콘텐츠를 생산 가공합니다.",
    "콘텐츠 사업이란 기획과 제작, 유통을 통칭하는 것으로 고객사는 뉴스콘텐츠를 생산 가공합니다.",
    "콘텐츠 사업이란 기획과 제작, 유통을 통칭하는 것으로 당사의 자회사는 뉴스콘텐츠를 생산 가공합니다.",
    "콘텐츠 사업이란 기획과 제작, 유통을 통칭하는 것으로 경쟁사는 뉴스콘텐츠를 생산 가공합니다.",
    "다른기업의 사업 개요: 콘텐츠 사업이란 기획과 제작, 유통을 통칭하는 것으로 당사는 뉴스콘텐츠를 생산 가공합니다.",
    "당사는 뉴스콘텐츠를 생산 가공할 계획입니다.",
    "당사는 뉴스콘텐츠를 생산 가공할 수 있습니다.",
    "당사는 정밀부품을 생산하는 경우 수익을 인식합니다.",
    "회사는 내부 관리시스템을 운영합니다.",
    "회사는 임직원에게 건강지원 서비스를 제공합니다.",
    "당사는 회계관리 서비스를 제공합니다.",
    "회사는 공시업무를 제공합니다.",
    "회사는 상품을 제공합니다.",
    "당사는 정밀부품을 생산한다고 과거 보고서에서 설명했다.",
    "당사는 거래처가 정밀부품을 생산한다고 설명합니다.",
    "당사는 고객사가 정밀부품을 생산한다고 설명합니다.",
    "당사는 거래처가 정밀부품을 생산합니다.",
    "당사는 고객사가 정밀부품을 생산합니다.",
    "당사는 과거 정밀부품을 생산한다고 공시했다.",
    "콘텐츠 사업이란 기획과 제작을 통칭하는 것으로 당사는 과거 뉴스콘텐츠를 생산 가공한다고 설명했다.",
))
def test_정의_타주체_미래_회계_관리_운영만으로_사업을_확정하지_않음(text):
    assert current_business_item(fragment(text), "가온기업") == ""


def test_정상_제휴칸을_운영사업_앵커로_자동_사용하지_않음():
    text = "당사는 정밀부품을 생산합니다."
    assert current_business_item(fragment(text, "operations_partners:partnership"), "가온기업") == ""
