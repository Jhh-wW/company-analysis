"""공시 «글의 생김새»를 알아보는 판정 — 여러 feature가 같이 쓴다.

★ 왜 `core/`에 있나 — 이 판정을 **두 feature가 쓴다** (프로젝트 규칙: 「feature 간
  직접 import 금지, 공유는 `core/` 경유. `shared` 진입 기준은 2개 이상이 실제로 쓸 때」).

    · `features/filingclean` — 목차면 **되살리려고** 본다 (다음 출현을 찾는다)
    · `features/grading`     — 목차면 **내보내지 않으려고** 본다 (최종 판정)

  목적이 반대라 한 feature로 합칠 수 없다. 그래서 «판정»만 여기 두고 각자 쓴다.

⚠️ **이 판정을 각 feature에 복사해 두면 안 된다.** 한쪽만 고쳐지는 순간
  「앞단은 목차로 보는데 뒷단은 아닌」 상태가 되고, 그게 정확히 P-83에서 겪은 사고다.
"""

from __future__ import annotations

import re
from typing import Final

#: 목차 판정 — 「점선 + 쪽번호」가 여러 번 반복되면 목차다.
#: ★ 낱말이 아니라 «모양»으로 본다. 목차의 특징은 낱말이 아니라
#:   「제목 … 쪽번호」가 줄줄이 이어지는 «생김새»다.
#: ⚠️ **점선 모양이 회사마다 다르다** (문제로그 P-103). 처음에는 붙임표(`---`)만 봤는데,
#:   실제 공시에는 가운뎃점(`‥‥‥`)·마침표(`.....`)·점(`···`)도 흔하다.
#:   붙임표만 보던 동안 **로보스타는 조각 9개 중 5개가 목차인데 전부 «본문»으로 통과**했다.
TOC_LEADERS: Final[str] = "-‥…·．."
TOC_LINE_RE: Final[re.Pattern[str]] = re.compile(rf"[{TOC_LEADERS}]{{3,}}\s*\d+")

#: 목차인지 볼 때 «앞부분만» 본다 (글자 수).
#: ★ 왜 앞만 보나 — 이 버그의 정체는 「표제의 **첫 출현**이 목차라서 거기서 떴다」이다.
#:   즉 목차 조각은 **목차로 시작한다.** 반대로 「본문으로 시작해 뒤에 목차가 섞인」
#:   조각은 **쓸 문장이 앞에 있으므로 건드리면 손해**다.
#:   실측 — 카카오모빌리티 특수관계자 조각이 정확히 그 경우였다(앞은 거래 내역, 뒤에 목차).
#:   전체를 보면 그것까지 목차로 잘못 판정한다.
TOC_HEAD_CHARS: Final[int] = 400

#: 몇 번 반복돼야 목차로 볼지.
#: ★ 3으로 잡은 이유 — 본문에도 「----- 2」 같은 게 한두 번 나올 수 있다.
#:   3번 이상 이어지면 본문에서는 사실상 안 나온다.
#:   실측 — 저장 조각 238개로 확인: **목차 14개**를 잡고 **오거부 0건**.
#:   ⚠️ 붙임표만 보던 때는 6개만 잡혔다. 「6개」라고 적었던 옛 수치는 **틀렸다** —
#:     나머지 8개(주로 로보스타·마침표 리더)를 «본문»으로 놓치고 있었다.
TOC_MIN_HITS: Final[int] = 3


def is_table_of_contents(text: str) -> bool:
    """이 글이 «목차»인가.

    Args:
        text: 조각이나 문장 원문.

    Returns:
        목차로 보이면 True.

    ★ 「본문에 목차가 섞였나」가 아니라 「이 덩어리가 목차인가」를 본다.
      앞부분만 목차이고 뒤는 본문인 경우도 있는데, 그건 **버리지 않는다** —
      쓸 문장이 뒤에 있기 때문이다. 그래서 **앞부분만** 보고 반복 «횟수»로 센다.
    """
    return len(TOC_LINE_RE.findall((text or "")[:TOC_HEAD_CHARS])) >= TOC_MIN_HITS
