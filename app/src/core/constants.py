# 내부 호환 키 ``附``는 기존 저장 자료 파서에서 유지한다. 다만 기본 내장 PDF
# 글꼴에 이 한자 글리프가 없어 화면·내보내기 제목에는 검색 가능한 한글을 쓴다.
CELL_DISPLAY_PREFIXES: Final[dict[str, str]] = {"附": "참고"}


def section_display_parts(cell: str, title: str) -> tuple[str, str]:
    """표시 제목에서 레거시 ``附`` 접두어가 중복되지 않게 나눈다."""

    prefix = CELL_DISPLAY_PREFIXES.get(cell, cell)
    clean_title = str(title).strip()
    if cell == "附" and clean_title.startswith(f"{prefix} "):
        clean_title = clean_title[len(prefix) :].strip()
    return prefix, clean_title


def section_display_heading(cell: str, title: str) -> str:
    """PDF·DOCX·Notion이 함께 쓰는 검색 가능한 섹션 제목을 만든다."""

    prefix, clean_title = section_display_parts(cell, title)
    separator = " " if cell == "附" else ". "
    return f"{prefix}{separator}{clean_title}".strip()

