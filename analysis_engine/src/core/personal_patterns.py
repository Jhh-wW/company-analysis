"""개인 신상 「값」 정규식 — 2층(posting_gate 값 조합 검사)과 3층(privacy_filter 지우개)이 공유.

정본: 확정/기획서/01_식별/04_공고판별규칙.md
  · 휴대전화: 01X 계열 + 구분자 없는 표기(01012345678) 포함.
    유선(02~)·안심번호(050)·국제 표기(+82)는 1차 검출 범위 미결 — 여기 넣지 않는다.
  · 생년월일: 연·월·일 값 표기. **출생 가능 연도(1900~2011)로 제한한다** —
    공고의 접수 마감일(2026년 8월 31일…)은 생년월일이 아니다. 제한이 없으면
    정상 공고가 2층 값 조합(날짜+전화)에 오차단되고 3층이 접수기간을 지워버린다
    (독립 검증 실측). 상한 2011 = 최저 근로 연령 15세(2026 기준) 출생연도.

두 층이 서로 다른 「값」 정의를 쓰면 2층을 통과한 값이 3층에서 새는 틈이 생긴다.
그래서 정의를 core에 한 벌만 둔다 (feature 간 직접 import 금지 규칙).

구분자 방침 (독립 검증 반영): 사람들이 실제 쓰는 표기는 「010 - 0000 - 7742」처럼
구분자가 여러 글자고, en-dash(–)·em-dash(—)·물결(~)·슬래시(/)도 쓴다. 그래서 구분자를
「집합 {0,3}개」로 받고, 숫자 경계((?<!\\d)·(?!\\d))로 문서번호(제2019-0123456호) 오인을 막는다.
"""
from __future__ import annotations

import re
import unicodedata

# 전각 숫자(０１０)·원문자 등은 NFKC 정규화로 반각화하고, 제로폭 문자는 지운 뒤 검사한다
_ZERO_WIDTH_RE = re.compile("[\u200b\u200c\u200d\ufeff]")


def normalize_for_scan(text: str) -> str:
    """검출 전 정규화 — NFKC(전각→반각) + 제로폭 문자 제거. 2층·3층 공용."""
    return _ZERO_WIDTH_RE.sub("", unicodedata.normalize("NFKC", text))


# 값 구분자 — 공백·하이픈류(‐–—)·점·물결·슬래시·가운뎃점·밑줄
_SEP = r"[\s\-‐–—.~/·_]"

# 생년월일 값 — 4자리 출생연도(1900~2011) 또는 2자리 연도(40~99·00~11, 년월일 표기 한정)
# 끝은 [ ]?일? — \s?로 두면 개행까지 삼켜 다음 줄이 붙는다(독립 검증 실측)
# 두 분기 모두 (?<!\d) 필수 — 없으면 「1899년」의 꼬리 「99년」만 따로 잡혀 4자리 연도가
# 부분 삭제된다(2차 독립 검증 실측: 1899·2044·2100·9999 전부 재현)
BIRTH_VALUE_RE = re.compile(
    r"(?<!\d)(?:19\d{2}|200\d|201[01])\s?[.년\-‐–—/]\s?\d{1,2}\s?[.월\-‐–—/]\s?\d{1,2}[ ]?일?"
    r"|(?<!\d)(?:[4-9]\d|0\d|1[01])년\s?\d{1,2}월\s?\d{1,2}일"
)

# 휴대전화 값 — 구분자 {0,3}개 · 괄호 국번((010)·[010]) · 그룹별 괄호 감쌈 ·
# 중간/끝 자리를 한 번 쪼갠 표기(00 00·77 42)까지
PHONE_VALUE_RE = re.compile(
    rf"(?<!\d)[\[(]?01[016789][\])]?{_SEP}{{0,3}}"
    rf"[\[(]?(?:\d{{3,4}}|\d{{2}}\s\d{{2}})[\])]?{_SEP}{{0,3}}"
    rf"[\[(]?(?:\d{{4}}|\d{{2}}\s\d{{2}})[\])]?(?!\d)"
)
